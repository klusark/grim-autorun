"""Writes stub.h for grimlaunch.cpp: the three logging stubs of launch.py, assembled for a fixed memory layout.

usage (from the grim_tools folder): python -m patches.launcher.gen_stub
Needs `as` and `objcopy` (binutils). The layout constants below are the same as in grimlaunch.cpp.
"""
import os

from ..launch import ARENA, log_stub
from ..grim import debuglog

# the exe's own import table (Grim Fandango v1.01), as launch.py reads it from the exe
IAT = dict(lua2C=0x4d7234, isstring=0x4d72a0, getstring=0x4d729c, createfile=0x4d70cc, writefile=0x4d7150, closehandle=0x4d7144)
DATA = ARENA + 0x800
PATH = DATA                   # the log path, written by the launcher (MAX_PATH)
PREFIXES = (DATA + 0x120, DATA + 0x130, DATA + 0x140)  # "ERROR ", "WARN  ", "DEBUG ": same order as debuglog.SLOTS
NEWLINE = DATA + 0x150
SCRATCH = DATA + 0x160


def main():
    out = ["// generated by gen_stub.py, do not edit", "#pragma once", "static const unsigned char STUBS[%d][%%d] = {" % len(debuglog.SLOTS)]
    stubs = [log_stub(IAT, PATH, p, 6, NEWLINE, SCRATCH) for p in PREFIXES]
    size = max(len(s) for s in stubs)
    out[-1] = out[-1] % size
    for s in stubs:
        out.append("\t{%s}," % ",".join("0x%02x" % b for b in s.ljust(size, b"\x90")))
    out.append("};")
    out.append("static const unsigned STUB_SIZE = %d;" % size)
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "stub.h")
    open(path, "w").write("\n".join(out) + "\n")
    print("wrote", path, size, "bytes a stub")


if __name__ == "__main__":
    main()
