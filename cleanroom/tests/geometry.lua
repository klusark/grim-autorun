-- Sector geometry: shrinking, nearest points, the opposite edge, sectors of points and actors, walks over edges

cr_shrink = function(key, x, y, z, r)
	local sx, sy, sz = GetShrinkPos(x, y, z, r)
	cr_log(key, sx, sy, sz)
end

cr_t_shrink_pos = function()
	MakeCurrentSet("cr_flat.set")
	cr_frames(1)
	cr_shrink("flat_centre", 0, 0, 0, 0.3)
	cr_shrink("flat_near_edge", 1.9, 0, 0, 0.3)
	cr_shrink("flat_corner", 1.95, 1.95, 0, 0.3)
	cr_shrink("flat_outside", 3, 1, 0, 0.3)
	cr_shrink("flat_big_r", 0, 0, 0, 2.5)
	MakeCurrentSet("cr_edge.set")
	cr_frames(1)
	cr_shrink("edge_shared", 0, 0, 0, 0.3)
	cr_shrink("edge_gap", 0, 2.00001, 0, 0.3)
	cr_shrink("edge_wedge", 3.9, -0.1, 0, 0.3)
	cr_shrink("edge_off", 0, -3, 0, 0.3)
	MakeCurrentSet("cr_stair.set")
	cr_frames(1)
	cr_shrink("stair_ramp", 1.9, 0.5, 0.25, 0.3)
	cr_shrink("stair_hot", 1.5, -2.5, 0, 0.3)
end
cr_test("shrink_pos", cr_t_shrink_pos)

cr_t_shrink_boxes = function()
	MakeCurrentSet("cr_flat.set")
	cr_frames(1)
	ShrinkBoxes(0.5)
	cr_point("shrunk_centre", 0, 0, 0)
	cr_point("shrunk_1_6", 1.6, 0, 0)
	cr_point("shrunk_1_4", 1.4, 0, 0)
	UnShrinkBoxes()
	cr_point("unshrunk_1_6", 1.6, 0, 0)
	MakeCurrentSet("cr_edge.set")
	cr_frames(1)
	ShrinkBoxes(0.5)
	cr_point("edge_shrunk_shared", 0, 0, 0)
	cr_point("edge_shrunk_left_wall", -1.6, 0, 0)
	cr_point("edge_shrunk_wedge", 3.6, -1, 0)
	UnShrinkBoxes()
end
cr_test("shrink_boxes", cr_t_shrink_boxes)

cr_t_actor_sectors = function()
	local a = cr_actor("cr_stair.set")
	cr_frames(1)
	PutActorAt(a, 0, -1, 0)
	cr_log("lo_walk", GetActorSector(a, 4096))
	cr_log("lo_in_lo", IsActorInSector(a, "lo"), IsActorInSector(a, "hi"))
	PutActorAt(a, 1.5, -2.5, 0)
	cr_log("hot_walk", GetActorSector(a, 4096))
	cr_log("hot_hot", GetActorSector(a, 8192))
	cr_log("in_hot", IsActorInSector(a, "hot"))
	PutActorAt(a, 0, 0.5, 0.25)
	cr_log("ramp", GetActorSector(a, 4096))
	PutActorAt(a, 5, 5, 0)
	cr_pos("put_outside", a)
	cr_log("outside_sector", GetActorSector(a, 4096))
end
cr_test("actor_sectors", cr_t_actor_sectors)

-- (closures cannot see locals: the actor a wait looks at is the global CR_A)
cr_not_moving_a = function()
	return not IsActorMoving(CR_A)
end

cr_actor_global = function(set)
	CR_A = cr_actor(set)
	return CR_A
end

cr_t_walk_outside = function()
	local a = cr_actor_global("cr_flat.set")
	SetActorWalkRate(a, 2)
	cr_frames(1)
	WalkActorTo(a, 3, 0.5, 0)
	break_here()
	local f = cr_until(cr_not_moving_a, 200)
	cr_log("frames", f)
	cr_pos("end", a)
end
cr_test("walk_outside", cr_t_walk_outside)

-- (one walk in cr_edge from (x0, y0) to (x1, y1))
cr_walk_case = function(key, x0, y0, x1, y1)
	local a = cr_actor_global("cr_edge.set")
	SetActorWalkRate(a, 2)
	PutActorAt(a, x0, y0, 0)
	cr_frames(1)
	WalkActorTo(a, x1, y1, 0)
	break_here()
	local f = cr_until(cr_not_moving_a, 300)
	cr_log(key .. "_frames", f)
	cr_pos(key .. "_end", a)
	cr_log(key .. "_sector", GetActorSector(a, 4096))
end

-- (over the shared edge, to e_gap over the 2e-5 gap, into the wedge, towards the floor that is off)
cr_t_walk_edges = function()
	cr_walk_case("shared", -1, 0, 1, 0.5)
	cr_walk_case("to_gap", 0, 1, 0, 3)
	cr_walk_case("to_wedge", 1, -1.5, 3.5, -1.5)
	cr_walk_case("into_off", 0, -1, 0, -3)
end
cr_test("walk_edges", cr_t_walk_edges)

cr_t_opposite_edge = function()
	local a = cr_actor("cr_edge.set")
	cr_frames(1)
	PutActorAt(a, -0.5, 0.5, 0)
	cr_log("ret_left", GetSectorOppositeEdge(a, "e_left"))
	cr_pos("after_left", a)
	PutActorAt(a, 0.5, 0.5, 0)
	cr_log("ret_right", GetSectorOppositeEdge(a, "e_right"))
	cr_pos("after_right", a)
	cr_log("ret_none", GetSectorOppositeEdge(a, "no_such"))
end
cr_test("opposite_edge", cr_t_opposite_edge)
