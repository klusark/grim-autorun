-- The camera of a setup and the projection of points (the setups of assets.py: 6 m above, looking down, fov 60)

cr_t_camera = function()
	MakeCurrentSet("cr_flat.set")
	cr_frames(1)
	local fov, x, y, z, roll = GetCameraPosition()
	cr_log("position", x, y, z)
	cr_log("fov_roll", fov, roll)
	cr_log("setup", GetCurrentSetup("cr_flat.set"))
	cr_log("screen_origin", WorldToScreen(0, 0, 0))
	local sx, sy = WorldToScreen(1, 1, 0)
	cr_log("screen_1_1", sx, sy)
	sx, sy = WorldToScreen(-2, -2, 0)
	cr_log("screen_m2_m2", sx, sy)
	sx, sy = WorldToScreen(0, 0, 3)
	cr_log("screen_up3", sx, sy)
	sx, sy = WorldToScreen(10, 0, 0)
	cr_log("screen_far_right", sx, sy)
end
cr_scummvm_differs("camera") cr_test("camera", cr_t_camera)
