-- the game's music_state (music_state.paused, music_state:pause()) across a Load: ScummVM's postRestoreHandle sets paused
-- to false and calls pause again
cr_scummvm_differs("gl1_music_state_load", "postRestoreHandle sets music_state.paused to false and calls pause (lua_v1.cpp:1147-1162); the original does not") cr_test("gl1_music_state_load", function()
	cr_save_clean()
	music_state = { paused = 1, calls = 0 }
	music_state.pause = function(self)
		self.calls = self.calls + 1
	end
	WriteRegistryValue("CrSavePass", "saving")
	cr_save("crgl1ms.gsv")
	if ReadRegistryValue("CrSavePass") == "saving" then
		WriteRegistryValue("CrSavePass", "loading")
		music_state.calls = 0
		Load("crgl1ms.gsv")
		cr_frames(10)
		cr_log("not_loaded", 1)
	else
		cr_log("pass", ReadRegistryValue("CrSavePass"))
		WriteRegistryValue("CrSavePass", "done")
		cr_frames(1)
		cr_log("paused", music_state.paused)
		cr_log("calls", music_state.calls)
	end
	music_state = nil
end)

