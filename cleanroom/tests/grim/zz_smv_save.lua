-- A save made while a movie plays (cr_white.snm of assets.py: 90 white frames, 6 s, at 100, 50), then loaded after the
-- movie was stopped: does the movie play again after the Load, where, and does it end? (cr_save is save.lua's; the Lua
-- goes on after the Save a second time, after the Load: the registry's SmvSavePass tells the two apart)
cr_scummvm_differs("smv_save_movie", "in the whole run ScummVM ends with 0xC0000409 (a stack buffer overrun) in this save while a movie plays") cr_test("smv_save_movie", function()
	cr_allow_frames(1000000000)
	MakeCurrentSet("cr_flat.set")
	cr_frames(2)
	PurgeText()
	StartMovie("cr_white.snm", nil, 100, 50)
	smv_wait_s(2)
	WriteRegistryValue("SmvSavePass", "saving")
	cr_save("smvsave.gsv")
	if ReadRegistryValue("SmvSavePass") == "saving" then
		WriteRegistryValue("SmvSavePass", "loading")
		cr_log("saved_playing", IsMoviePlaying())
		StopMovie()
		cr_frames(3)
		cr_log("stopped", IsMoviePlaying())
		Load("smvsave.gsv")
		cr_frames(10)
		cr_log("not_loaded", 1)
	else
		cr_log("pass", ReadRegistryValue("SmvSavePass"))
		WriteRegistryValue("SmvSavePass", "done")
		cr_frames(3)
		cr_log("loaded_playing", IsMoviePlaying())
		smv_wait_s(2)
		cr_log("loaded_playing_later", IsMoviePlaying())
		cr_snap("loaded_snap")
		cr_log("ended", smv_wait_end(10))
	end
	StopMovie()
	cr_frames(3)
end)
