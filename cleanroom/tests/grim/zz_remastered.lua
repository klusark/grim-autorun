-- The Remastered's own builtins (Lua_Remastered in ScummVM's Remastered mode, run.py scummvm --remastered; the Remastered
-- exe, run.py remastered): each called with plausible arguments, one test each, what it gives logged. The original and
-- ScummVM's Grim mode have none of them: each test logs "missing" there. Last of the tests (after the saves).

cr_rem_test = function(name, fn)
	cr_test("rem_" .. name, function()
		-- (the builtin is the name up to a "_": ReadRegistryIntValue_missing calls ReadRegistryIntValue)
		local b = %name
		local i = strfind(b, "_")
		if i then
			b = strsub(b, 1, i - 1)
		end
		if not getglobal(b) then
			cr_log("missing", 1)
			return
		end
		cr_log("r", %fn())
	end)
end

