-- iMUSE playing for seconds of the clock (cr_wait_s of movie.lua): the music of music.lua (states, the hook jump of 1002,
-- 1008 in MCMP with VIMA, the sequence 2001 and its "_end" marker), a sound's fade and a voiced line with lip sync
-- (lipsync.lua's crtv01). The original plays on NULLMUSE.DLL, with no sound driver, and does not move a sound on; ScummVM's
-- iMUSE plays by real time. What is logged is what does not depend on how far a sound got: that the changes ran, and the
-- state after everything is stopped.

cr_live_test = function(name, fn)
	cr_test("live_" .. name, function()
		cr_allow_frames(1000000000)
		ImStopAllSounds()
		ImSetSequence(2000)
		ImSetState(1000)
		cr_frames(2)
		%fn()
		ImStopAllSounds()
		ImSetSequence(2000)
		ImSetState(1000)
		cr_frames(2)
		cr_log("after", cr_im("cr_tone.wav"), cr_im("cr_long.wav"))
	end)
end

-- the states, one after another, with seconds of each
cr_live_test("states", function()
	ImSetState(1001)
	cr_wait_s(2)
	ImSetState(1002)
	cr_wait_s(2)
	-- (1003 is the same file as 1002, with the hook that takes its jump)
	ImSetState(1003)
	cr_wait_s(2)
	ImSetState(1008)
	cr_wait_s(3)
	ImSetState(1001)
	cr_wait_s(1)
	cr_log("ok", 1)
end)

-- a sequence over a state: it plays to its "_end" marker and ends
cr_live_test("sequence", function()
	ImSetState(1008)
	cr_wait_s(1)
	ImSetSequence(2001)
	cr_wait_s(3)
	ImSetSequence(2000)
	cr_wait_s(1)
	cr_log("ok", 1)
end)

-- the music's volume while it plays
cr_live_test("music_volume", function()
	local v = ImGetMusicVol()
	ImSetState(1001)
	cr_wait_s(1)
	ImSetMusicVol(30)
	cr_wait_s(1)
	ImSetMusicVol(v)
	cr_wait_s(1)
	cr_log("ok", 1)
end)

-- a sound to its end, and one faded out and panned while it plays
cr_live_test("sounds", function()
	ImStartSound("cr_tone.wav", 127, 1)
	cr_wait_s(2)
	ImStartSound("cr_long.wav", 100, 1)
	cr_wait_s(1)
	ImFadeParam("cr_long.wav", CR_IM_VOL, 0, 1000)
	ImSetParam("cr_long.wav", CR_IM_PAN, 10)
	cr_wait_s(2)
	ImStartSound("cr_long.wav", 100, 1)
	cr_wait_s(1)
	ImSetParam("cr_long.wav", CR_IM_PRIO, 20)
	ImStartSound("cr_tone.wav", 110, 2)
	cr_wait_s(2)
	cr_log("ok", 1)
end)

-- a voiced line with lip sync, for seconds (ScummVM moves the lip sync on with the voice)
cr_live_test("voice", function()
	local a = cr_talker()
	SayLine(a, "/crtv01/", { x = 100, y = 100 })
	cr_wait_s(2)
	ShutUpActor(a)
	cr_frames(2)
	cr_log("shut_up", CR_LV, IsMessageGoing())
	PutActorInSet(a, nil)
	ExpireText()
	cr_frames(1)
end)

