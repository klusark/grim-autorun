-- ---------------------------------------------------------------- movies (cr_steps: 5 frames at 15 a second)

-- (until the movie stops, at most about n seconds)
elu_movie_wait = function(n)
	local s = date("%S")
	while n > 0 and IsMoviePlaying() do
		break_here()
		local t = date("%S")
		if t ~= s then
			s = t
			n = n - 1
			PrintDebug("wait\n")
		end
	end
	return not IsMoviePlaying()
end

