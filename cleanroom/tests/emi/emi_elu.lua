-- EMI's Lua builtins doing their work (lua_v2.cpp, lua_v2_actor.cpp, emi.cpp): actors after UnloadActor, chores played,
-- paused, advanced, stopped with a fade, chores of an unloaded actor, the look at, the turn chores, walks avoiding and by a
-- vector, setups by name, WorldToScreen, layers and their frames (elu_frames.til: three layers), the text stack, the CD,
-- bundles, movies escaped, the save-game builtins, RenderModeUser. The original's EMI gives no picture in the clean room:
-- what Lua reads back is logged. A few builtins exist only on ScummVM (GetMemoryCardId, OverWorldToScreen, SetReplayMode,
-- IsActorChoring, GetResidualVMPreference): their tests log "missing" on the original and are marked.

-- (ScummVM only: its own preference builtins)
ELU_SVM = GetResidualVMPreference

-- (an actor in the set, at the origin, following the boxes)
elu_actor = function(name, set)
	if not set then
		set = "cr_flat.set"
	end
	MakeCurrentSet(set)
	local a = LoadActor(name)
	PutActorInSet(a, set)
	PutActorAt(a, 0, 0, 0)
	SetActorRot(a, 0, 0, 0)
	SetActorFollowBoxes(a, TRUE)
	return a
end

-- (an actor's handle after UnloadActor)
elu_gone = function(name)
	local a = elu_actor(name)
	UnloadActor(a)
	return a
end

-- (the values as one string)
elu_s = function(a, b, c, d)
	return tostring(a) .. " " .. tostring(b) .. " " .. tostring(c) .. " " .. tostring(d)
end

-- (CR_LV and IsChorePlaying every frame, n frames, as one string)
elu_trace = function(c, n)
	local s = ""
	local f = 0
	while f < n do
		s = s .. tostring(CR_LV) .. "/" .. tostring(IsChorePlaying(c)) .. " "
		break_here()
		f = f + 1
	end
	return s
end

-- (the yaw, pitch, roll as one string)
elu_rot = function(a)
	local x, y, z = GetActorRot(a)
	return elu_s(x, y, z)
end

-- (all the results of f(p, q, r), at most four, logged under key: a call in an argument list gives only its first result)
elu_call = function(key, f, p, q, r)
	local r1, r2, r3, r4 = f(p, q, r)
	cr_log(key, r1, r2, r3, r4)
end

-- (a point on the screen, both values)
elu_w2s = function(key, x, y, z)
	local u, v, w = WorldToScreen(x, y, z)
	cr_log(key, u, v, w)
end

elu_pos = function(key, a)
	local x, y, z = GetActorPos(a)
	cr_log(key, x, y, z)
end

