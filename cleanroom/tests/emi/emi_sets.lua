-- EMI's sets, setups and sectors (assets_emi.py): binary .setb, the floor in the x-z plane, y up
-- (the sets are Grim's turned over: Grim's y is EMI's z. A point is given as x, y (height), z)

cr_es_sector = function(key, x, y, z, t)
	local id, name, typ = GetPointSector(x, y, z, t)
	cr_log(key, id, name, typ)
end

cr_t_es_load = function()
	MakeCurrentSet("cr_flat.set")
	cr_log("setup", GetCurrentSetup("cr_flat.set"))
	cr_es_sector("centre", 0, 0, 0)
	cr_es_sector("inside", 1.5, 0, -1.5)
	cr_es_sector("corner", 2, 0, 2)
	cr_es_sector("outside", 3, 0, 0)
	cr_es_sector("above", 0, 1, 0)
	cr_es_sector("below", 0, -1, 0)
	cr_es_sector("far_above", 0, 100, 0)
	cr_log("name", GetSectorName(0, 0, 0))
	cr_log("name_outside", GetSectorName(3, 0, 0))
end
cr_scummvm_differs("es_load") cr_test("es_load", cr_t_es_load)

