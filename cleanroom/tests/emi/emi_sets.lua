cr_t_es_setups = function()
	MakeCurrentSet("cr_two.set")
	cr_log("first", GetCurrentSetup("cr_two.set"))
	MakeCurrentSetup(1)
	cr_log("second", GetCurrentSetup("cr_two.set"))
	MakeCurrentSetup(0)
	cr_log("back", GetCurrentSetup("cr_two.set"))
	cr_frames(1)
	cr_es_sector("sector", 0, 0, 0)
end
cr_test("es_setups", cr_t_es_setups)

cr_t_es_switch = function()
	MakeCurrentSet("cr_flat.set")
	cr_es_sector("flat", 1, 0, 0)
	cr_frames(2)
	MakeCurrentSet("cr_edge.set")
	cr_es_sector("edge", 1, 0, 0)
	cr_frames(2)
	MakeCurrentSet("cr_flat.set")
	cr_es_sector("flat_again", 1, 0, 0)
	cr_log("setup", GetCurrentSetup("cr_flat.set"))
end
cr_test("es_switch", cr_t_es_switch)
