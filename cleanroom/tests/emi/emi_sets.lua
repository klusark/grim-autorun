cr_t_es_active = function()
	MakeCurrentSet("cr_edge.set")
	cr_log("left_active", IsSectorActive("e_left"))
	cr_log("off_active", IsSectorActive("e_off"))
	MakeSectorActive("e_left", FALSE)
	cr_log("left_after_off", IsSectorActive("e_left"))
	cr_es_sector("left_off", -1, 0, 0)
	MakeSectorActive("e_off", TRUE)
	cr_log("off_after_on", IsSectorActive("e_off"))
	cr_es_sector("off_on", 0, 0, -3)
	MakeSectorActive("e_left", TRUE)
	cr_es_sector("left_on", -1, 0, 0)
	cr_log("unknown", IsSectorActive("no_such_sector"))
end
cr_scummvm_differs("es_active") cr_test("es_active", cr_t_es_active)

