-- EMI's attached actors (AttachActor(rider, carrier, joint), DetachActor): a rider without a costume on cr_ebox.cos's
-- skeleton (its joint "body" is 0.9 m up; the lift chore moves it 0.5 m up and turns the root a quarter about y). Seen
-- through GetActorWorldPos and GetActorPos. Then the carrier's alpha (SetActorGlobalAlpha, SetActorLocalAlpha).

cr_ea_wpos = function(key, a)
	local x, y, z = GetActorWorldPos(a)
	cr_log(key, x, y, z)
end

cr_eat_pair = function()
	local c = cr_ea_actor("cr_flat.set")
	PutActorAt(c, 1, 0, 0)
	PlayActorChore(c, "wear_default", "cr_ebox.cos")
	local r = LoadActor("cr_rider")
	PutActorInSet(r, "cr_flat.set")
	PutActorAt(r, 0, 0, 0)
	SetActorRot(r, 0, 0, 0)
	cr_frames(2)
	return c, r
end

cr_test("eat_joint", function()
	local c, r = cr_eat_pair()
	AttachActor(r, c, "body")
	cr_frames(2)
	cr_ea_wpos("attached", r)
	cr_ea_pos("attached_pos", r)
	PutActorAt(c, 2, 0, 1)
	cr_frames(2)
	cr_ea_wpos("carrier_moved", r)
	SetActorRot(c, 0, 90, 0)
	cr_frames(2)
	cr_ea_wpos("carrier_turned", r)
	PlayActorChore(c, "lift", "cr_ebox.cos")
	cr_frames(70)
	cr_ea_wpos("lifted", r)
	DetachActor(r)
	cr_frames(2)
	cr_ea_wpos("detached", r)
	cr_ea_pos("detached_pos", r)
	StopActorChores(c)
	PutActorInSet(r, nil)
	PutActorInSet(c, nil)
end)

-- attached without a joint, then attached again to another
cr_test("eat_nojoint", function()
	local c, r = cr_eat_pair()
	AttachActor(r, c, nil)
	cr_frames(2)
	cr_ea_wpos("attached", r)
	PutActorAt(c, -1, 0, 2)
	cr_frames(2)
	cr_ea_wpos("carrier_moved", r)
	DetachActor(r)
	DetachActor(r)
	cr_frames(1)
	cr_ea_wpos("detached_twice", r)
	StopActorChores(c)
	PutActorInSet(r, nil)
	PutActorInSet(c, nil)
end)

-- the carrier's alpha: the whole actor, then one of its meshes
cr_test("eat_alpha", function()
	local c, r = cr_eat_pair()
	SetActorGlobalAlpha(c, 0.5)
	cr_frames(2)
	SetActorGlobalAlpha(c, 1)
	SetActorLocalAlpha(c, 0, 0.25)
	SetActorLocalAlpha(c, 1, 0.75)
	cr_frames(2)
	SetActorLocalAlpha(c, 0, 1)
	cr_frames(1)
	cr_log("ok", 1)
	StopActorChores(c)
	PutActorInSet(r, nil)
	PutActorInSet(c, nil)
end)

-- the shadows of a set (cr_shadows.set: cr_shadow1 from the light, cr_shadow2 from a point): an actor with a mesh casts
-- them, one by name, all, then none (ActorActivateShadow(actor, active, shadow name))
cr_test("eat_shadow", function()
	MakeCurrentSet("cr_shadows.set")
	local a = LoadActor("cr_shadower")
	PutActorInSet(a, "cr_shadows.set")
	PutActorAt(a, 0, 0, 0)
	PlayActorChore(a, "wear_default", "cr_ebox.cos")
	cr_frames(2)
	ActorActivateShadow(a, 1, "cr_shadow1")
	cr_frames(2)
	ActorActivateShadow(a, 1)
	cr_frames(2)
	ActorActivateShadow(a, 1, "cr_no_such_shadow")
	ActorActivateShadow(a, 0, "cr_shadow1")
	cr_frames(2)
	ActorActivateShadow(a, 0)
	cr_frames(2)
	cr_log("ok", 1)
	StopActorChores(a)
	PutActorInSet(a, nil)
end)
