-- voices of 1.7 s in stereo (esnv01, stored samples), of 3 s (esnv02) and of 12 s (esnv03) in VIMA: going at once, after
-- 3 frames, some changes of the clock's second later (n changes: more than n - 1 seconds and at most n), and 4 changes
-- after that
esn_voice = function(id, seconds)
	local a = cr_ea_actor("cr_flat.set")
	SayLine(a, "/" .. id .. "/")
	cr_log("at_once", IsMessageGoing())
	cr_frames(3)
	cr_log("going", IsMessageGoing())
	esn_wait(seconds)
	cr_log("later", IsMessageGoing())
	esn_wait(4)
	cr_log("much_later", IsMessageGoing())
	ShutUpActor(a)
	cr_frames(2)
	cr_log("shut_up", IsMessageGoing())
	PutActorInSet(a, nil)
end

