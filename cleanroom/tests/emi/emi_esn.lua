-- AIFFs in stereo at 11025 Hz and in 8 bits at 44100 Hz
esn_format = function(name)
	local h = LoadSound(name)
	cr_log("handle", type(h))
	PlayLoadedSound(h, 1, 100)
	cr_frames(2)
	cr_log("playing", esn_state(h))
	StopSound(h)
	cr_frames(1)
	cr_log("stopped", esn_state(h))
	FreeSound(h)
end

