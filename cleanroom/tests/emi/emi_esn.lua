-- PlayLoadedSoundFrom(h, x, y, z, a, b): a looping flag and a volume, nil and a volume, a string and a volume
esn_from = function(key, a, b)
	MakeCurrentSet("cr_flat.set")
	local h = LoadSound("cr_long")
	PlayLoadedSoundFrom(h, 0, 0, 1, a, b)
	cr_frames(2)
	cr_log(key, esn_state(h))
	StopSound(h)
	cr_frames(1)
	cr_log(key .. "_stopped", esn_state(h))
	FreeSound(h)
end

