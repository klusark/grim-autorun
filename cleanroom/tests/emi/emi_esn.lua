-- EMI's sounds (prefix esn; assets_emi_extra_esn.py): the sound pool's handles after FreeSound, PlayLoadedSound and
-- PlayLoadedSoundFrom with each form of their arguments, a sound played twice, PlaySoundFrom's forms, wrong volumes and
-- positions, the volumes and switches of the groups, SetReverb, the pause of RenderModeUser, a positioned sound across
-- a change of setup, AIFFs in stereo and 8 bits and one that is not an AIFF, voices longer than 1 s and in stereo.
-- The sounds play by real time on both engines: the values are those of the start and after a stop, and of a voice
-- some seconds of the clock after it began.

-- (a sound's handle: playing, its volume)
esn_state = function(h)
	return tostring(IsSoundPlaying(h)) .. " " .. tostring(GetSoundVolume(h))
end

-- (n changes of the clock's second)
esn_wait = function(n)
	local s = date("%S")
	while n > 0 do
		break_here()
		local t = date("%S")
		if t ~= s then
			s = t
			n = n - 1
		end
	end
end

-- (a handle after FreeSound, then one call with it)
esn_freed = function(fn)
	local h = LoadSound("cr_tone")
	FreeSound(h)
	cr_frames(1)
	fn(h)
	cr_frames(2)
	cr_log("after", esn_state(h))
end

