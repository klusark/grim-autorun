-- EMI's camera turned through the current setup (PitchCamera, YawCamera, RollCamera with numbers: Setup::setPitch,
-- setYaw, setRoll), read back, then the setup made current again; SetActiveCD.

cr_t_ecc_turn = function()
	MakeCurrentSet("cr_flat.set")
	cr_frames(1)
	cr_log("before", GetCameraPitch(), GetCameraYaw(), GetCameraRoll())
	PitchCamera(10)
	cr_log("pitched", GetCameraPitch(), GetCameraYaw(), GetCameraRoll())
	YawCamera(20)
	cr_log("yawed", GetCameraPitch(), GetCameraYaw(), GetCameraRoll())
	RollCamera(5)
	cr_log("rolled", GetCameraPitch(), GetCameraYaw(), GetCameraRoll())
	cr_frames(1)
	cr_log("position", GetCameraPosition())
	PitchCamera(-30.5)
	YawCamera(370)
	RollCamera(-90)
	cr_log("odd", GetCameraPitch(), GetCameraYaw(), GetCameraRoll())
	MakeCurrentSet("cr_edge.set")
	cr_frames(1)
	MakeCurrentSet("cr_flat.set")
	cr_frames(1)
	cr_log("again", GetCameraPitch(), GetCameraYaw(), GetCameraRoll())
end
cr_scummvm_differs("ecc_turn", "the original turns the camera about its own axes (a pitch, then a yaw, then a roll compose) and keeps the turn in the setup when the set comes back; ScummVM sets each Euler angle alone (set.cpp:539-567) and the set made current again has its setup as loaded") cr_test("ecc_turn", cr_t_ecc_turn)

cr_t_ecc_cd = function()
	cr_log("cd1", SetActiveCD(1))
	cr_log("cd2", SetActiveCD(2))
	cr_log("cd3", SetActiveCD(3))
	cr_log("cd0", SetActiveCD(0))
	cr_log("active", GetActiveCD())
end
cr_scummvm_differs("ecc_cd", "SetActiveCD(2): nil on the original, which then gives 2 as the active CD; ScummVM gives 1 and its active CD stays 1 (lua_v2.cpp:194-203)") cr_test("ecc_cd", cr_t_ecc_cd)

-- seven shadows, five slots: all of them made active at once (the last two find no slot), then by name, then off
cr_t_ecc_shadow_slots = function()
	MakeCurrentSet("cov_shadows7.set")
	local a = LoadActor("cr_cov_shadower")
	PutActorInSet(a, "cov_shadows7.set")
	PutActorAt(a, 0, 0, 0)
	PlayActorChore(a, "wear_default", "cr_ebox.cos")
	cr_frames(2)
	ActorActivateShadow(a, 1)
	cr_frames(2)
	ActorActivateShadow(a, 1, "cov_shadow6")
	ActorActivateShadow(a, 0, "cov_shadow0")
	ActorActivateShadow(a, 1, "cov_shadow6")
	cr_frames(2)
	ActorActivateShadow(a, 0)
	cr_frames(2)
	cr_log("ok", 1)
	StopActorChores(a)
	PutActorInSet(a, nil)
end
cr_test("ecc_shadow_slots", cr_t_ecc_shadow_slots)
