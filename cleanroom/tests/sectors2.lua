-- Rules of sector switching and of points off the floor plane

cr_t_sector_active = function()
	MakeCurrentSet("cr_edge.set")
	cr_frames(1)
	cr_point("off_before", 0, -3, 0)
	MakeSectorActive("e_off", TRUE)
	cr_point("on_by_name", 0, -3, 0)
	MakeSectorActive("e_off", FALSE)
	cr_point("off_by_name", 0, -3, 0)
	MakeSectorActive("e_of", TRUE)
	cr_point("on_by_prefix", 0, -3, 0)
	MakeSectorActive("e_of", FALSE)
	MakeSectorActive("E_OFF", TRUE)
	cr_point("on_by_upper", 0, -3, 0)
	MakeSectorActive("E_OFF", FALSE)
	MakeSectorActive(3, TRUE)
	cr_point("on_by_id", 0, -3, 0)
	MakeSectorActive(3, FALSE)
	cr_point("off_by_id", 0, -3, 0)
	MakeSectorActive("e_left", FALSE)
	cr_point("left_off", -1, 0, 0)
	cr_point("shared_left_off", 0, 0, 0)
	MakeSectorActive("e_left", TRUE)
	cr_point("left_on", -1, 0, 0)
end
cr_test("sector_active", cr_t_sector_active)

-- (whether the set remembers a switched sector across a change of set)
cr_t_sector_active_kept = function()
	MakeCurrentSet("cr_edge.set")
	MakeSectorActive("e_off", TRUE)
	cr_frames(1)
	MakeCurrentSet("cr_flat.set")
	cr_frames(1)
	MakeCurrentSet("cr_edge.set")
	cr_frames(1)
	cr_point("off_after_return", 0, -3, 0)
	MakeSectorActive("e_off", FALSE)
end
cr_test("sector_active_kept", cr_t_sector_active_kept)

cr_t_point_heights = function()
	MakeCurrentSet("cr_stair.set")
	cr_frames(1)
	cr_point("lo_above", 0, -1, 1)
	cr_point("lo_below", 0, -1, -1)
	cr_point("hi_at_lo_height", 0, 2, 0)
	cr_point("hi_far_above", 0, 2, 10)
	cr_point("ramp_low", 0, 0.5, 0)
	cr_point("ramp_high", 0, 0.5, 0.5)
	cr_point("ramp_edge_lo", 0, 0, 0)
	cr_point("ramp_edge_hi", 0, 1, 0.5)
end
cr_test("point_heights", cr_t_point_heights)
