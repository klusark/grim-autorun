-- EMI's own builtins that need no costume: actor attributes, camera, overworld, layers, text, sound groups  -- games: emi

cr_ee_actor = function()
	MakeCurrentSet("cr_flat.set")
	local a = LoadActor("cr_attrs")
	PutActorInSet(a, "cr_flat.set")
	PutActorAt(a, 0, 0, 0)
	return a
end

cr_t_ee_sort_order = function()
	local a = cr_ee_actor()
	cr_log("default", GetActorSortOrder(a))
	SetActorSortOrder(a, 7)
	cr_log("set", GetActorSortOrder(a))
	SetActorSortOrder(a, -3)
	cr_log("negative", GetActorSortOrder(a))
	SetActorSortOrder(a, 2.6)
	cr_log("fraction", GetActorSortOrder(a))
end
cr_test("ee_sort_order", cr_t_ee_sort_order)

cr_t_ee_time_scale = function()
	local a = cr_ee_actor()
	cr_log("default", GetActorTimeScale(a))
	SetActorTimeScale(a, 2)
	cr_log("set", GetActorTimeScale(a))
	SetActorTimeScale(a, 0)
	cr_log("zero", GetActorTimeScale(a))
	SetActorTimeScale(a, 1)
	-- (a walk at twice the time)
	SetActorFollowBoxes(a, TRUE)
	SetActorWalkRate(a, 1)
	SetActorTimeScale(a, 2)
	WalkActorTo(a, 1.5, 0, 0)
	cr_frames(10)
	local x, y, z = GetActorPos(a)
	cr_log("walk_scaled", x, y, z)
end
cr_test("ee_time_scale", cr_t_ee_time_scale)

