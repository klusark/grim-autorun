cr_t_ee_overworld = function()
	ClearOverworld()
	local a = cr_ee_actor()
	PutActorInOverworld(a)
	ToggleOverworld(TRUE)
	cr_frames(1)
	local x, y, z = GetActorPos(a)
	cr_log("pos", x, y, z)
	ToggleOverworld(FALSE)
	RemoveActorFromOverworld(a)
	ClearOverworld()
	cr_frames(1)
	cr_log("ok", 1)
end
cr_test("ee_overworld", cr_t_ee_overworld)

cr_t_ee_layers = function()
	MakeCurrentSet("cr_flat.set")
	local l = NewLayer("cr_edge.til", 5, 0)
	cr_log("type", type(l))
	if l then
		cr_log("frame", GetLayerFrame(l))
		SetLayerFrame(l, 0)
		cr_log("frame_set", GetLayerFrame(l))
		cr_log("sort", GetLayerSortOrder(l))
		SetLayerSortOrder(l, 9)
		cr_log("sort_set", GetLayerSortOrder(l))
		cr_frames(1)
		FreeLayer(l)
	end
	cr_log("missing", NewLayer("no_such.til", 1, 0))
end
cr_test("ee_layers", cr_t_ee_layers)

