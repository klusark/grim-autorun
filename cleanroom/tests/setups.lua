-- A set with three setups (cr_cams.set): switching cameras, the camera values and projections of each, sector types

cr_cam_state = function(key)
	local fov, x, y, z, roll = GetCameraPosition()
	cr_log(key .. "_setup", GetCurrentSetup("cr_cams.set"))
	cr_log(key .. "_pos", x, y, z)
	cr_log(key .. "_fov_roll", fov, roll)
	local sx, sy = WorldToScreen(0, 0, 0)
	cr_log(key .. "_origin", sx, sy)
	sx, sy = WorldToScreen(1, -1, 0.5)
	cr_log(key .. "_point", sx, sy)
end

cr_t_setups = function()
	MakeCurrentSet("cr_cams.set")
	cr_frames(1)
	cr_cam_state("first")
	MakeCurrentSetup(1)
	cr_frames(1)
	cr_cam_state("one")
	MakeCurrentSetup(2)
	cr_frames(1)
	cr_cam_state("two")
	MakeCurrentSetup(0)
	cr_frames(1)
	cr_cam_state("zero")
	MakeCurrentSetup(7)
	cr_frames(1)
	cr_log("out_of_range", GetCurrentSetup("cr_cams.set"))
end
cr_test("setups", cr_t_setups)

cr_t_setup_kept = function()
	MakeCurrentSet("cr_cams.set")
	MakeCurrentSetup(2)
	cr_frames(1)
	MakeCurrentSet("cr_flat.set")
	cr_frames(1)
	MakeCurrentSet("cr_cams.set")
	cr_frames(1)
	cr_log("after_return", GetCurrentSetup("cr_cams.set"))
	cr_log("of_other_set", GetCurrentSetup("cr_flat.set"))
end
cr_test("setup_kept", cr_t_setup_kept)

cr_t_sector_types = function()
	MakeCurrentSet("cr_cams.set")
	cr_frames(1)
	local id, name, typ = GetPointSector(0, -1, 0)
	cr_log("walk", id, name, typ)
	id, name, typ = GetPointSector(0, -1, 0, 16384)
	cr_log("camera", id, name, typ)
	id, name, typ = GetPointSector(0, 0, 0, 32768)
	cr_log("special", id, name, typ)
	id, name, typ = GetPointSector(0, 1, 0, 16384)
	cr_log("camera_none", id, name, typ)
	cr_log("in_special", IsPointInSector(0, 0, 0, "special_spot"), IsPointInSector(0, -1.5, 0, "cam_south"))
end
cr_test("sector_types", cr_t_sector_types)
