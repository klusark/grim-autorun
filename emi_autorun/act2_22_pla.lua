-- Act 2 chapter 22: the plank diving competition: Marco, the judges (exploration)
ar_load(221)
ar_log("=== ACT2 ch22 pla ===")
ar_wait_for_control()
ar_put_away()
ar_do("use", gpt.jam_door)
ar_wait_for_control()
ar_do("use", jam.pla_door)
ar_wait_for(function() return ar_set_name() == "plank diving competition" end, 60000, "the diving competition")
sleep_for(3000)
-- (the arrival cutscene, skipped, can start Marco's conversation itself: then the cutscene level stays up while it runs, and the wait for
-- the control timed out (120 s, the run failed). The conversation is followed as it is; he is talked to only when it has not begun)
a2_mr1_up = function()
	local d = getglobal("mr1")
	return d and d.running
end
ar_try_wait(function() return cutSceneLevel == 0 or a2_mr1_up() end, 120000)
if a2_mr1_up() then
	ar_log("Marco's conversation began with the arrival")
else
	ar_wait_for_control()
	ar_talk(pla.marco_obj)
end
ar_dlg("mr1")
a2_ready("mr1", 5000)
ar_lines("mr1")
a2_pick_any("mr1", { 70, 80, 90, 95 })
a2_ready("mr1", 15000)
ar_lines("mr1")
ar_say("mr1", 130)
a2_ready("mr1", 12000)
ar_lines("mr1")
a2_leave("mr1")
ar_wait_for_control()
ar_check(glob.know_certification, "knows about the certificate")
-- the judges certify him
ar_talk(pla.judges)
ar_dlg("jd3")
a2_ready("jd3", 6000)
ar_lines("jd3")
ar_say("jd3", 70)
ar_dlg_done("jd3")
ar_wait_for_control()
ar_check(props.diving_certificate.state == PROP_INV, "diving certificate")
ar_state("certified")
ar_checkpoint(222)
