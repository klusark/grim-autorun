-- Act 2 chapter 25: the rematch: Marco dives first, the dunce cap on, Marco's moves copied: a tie, the tie-break (Marco's oil is spoiled and
-- the seagulls come): the trophy
ar_load(224)
ar_log("=== ACT2 ch25 dive2 ===")
ar_wait_for_control()
ar_put_away()
ar_talk(pla.marco_obj)
ar_dlg("mr1")
sleep_for(5000)
ar_lines("mr1")
a2_pick_any("mr1", { 150 })
a2_leave("mr1")
ar_wait_for(function() return pla.time_to_dive and cutSceneLevel == 0 and guybrush:getpos().y > 29 end, 300000, "Guybrush on the tower")
sleep_for(2000)
ar_log("marco did " .. glob.marco_did[1] .. "," .. glob.marco_did[2] .. "," .. glob.marco_did[3])
a2_use_held(props.dunce_cap)
ar_log("cap state " .. tostring(props.dunce_cap.state))
a2_dive(glob.marco_did[1], glob.marco_did[2], glob.marco_did[3])
ar_wait_for(function() return cutSceneLevel == 0 end, 300000, "the scores")
sleep_for(3000)
ar_wait_for_control()
ar_log("matched " .. tostring(glob.matched_marco) .. " tie_count " .. tostring(glob.tie_count) .. " second_round " .. tostring(pla.second_round))
ar_state("after the first round")
-- the tie-break: any three moves, then Marco (with the spoiled oil) has to match them
ar_log("cap state before round two " .. tostring(props.dunce_cap.state))
if props.dunce_cap.state == PROP_INV then
	a2_use_held(props.dunce_cap)
end
a2_dive(1, 3, 2)
ar_wait_for(function() return cutSceneLevel == 0 end, 300000, "the scores")
sleep_for(3000)
ar_wait_for_control()
-- (the trophy comes with the judges' talk; the three pieces together then end the act: the game sails for Melee and Act 3 begins)
ar_wait_for(function() return glob.curr_act == 3 and ar_set_name() == "monkey beach" end, 400000, "Act 3")
sleep_for(3000)
ar_wait_for_control()
ar_log("act " .. tostring(glob.curr_act) .. " set " .. ar_set_name() .. " trophy " .. tostring(props.trophy.state))
ar_check(glob.curr_act == 3, "Act 3 has begun")
ar_state("Act 3")
ar_checkpoint(225)
