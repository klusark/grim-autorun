-- EMI chapter 25: Pegnose Pete's hideout: grease the welcome mat, then throw the duck in at the window; Pegnose slips into the trap
ar_load(24)
ar_log("=== EMI ch25 hideout ===")
ar_wait_for_control()
-- listen at the front door: Ozzie and Pegnose inside (Ozzie is the one who hired him and framed Guybrush)
ar_do("use", pph.door)
ar_wait_for(function() return glob.guybrush_knows_ozzie_framed end, 120000, "the talk behind the door")
sleep_for(3000)
ar_wait_for_control()
ar_log("knows_ozzie_framed=" .. tostring(glob.guybrush_knows_ozzie_framed))
ar_survey()
ar_do("use", pph.mat, props.grease)
sleep_for(1500)
ar_wait_for_control()
ar_log("mat_greased=" .. tostring(glob.mat_greased))
ar_do("use", pph.window, props.duck)
ar_wait_for(function() return glob.caught_pegnose end, 90000, "Pegnose caught")
ar_wait_for_control()
ar_state("end")
ar_log("caught_pegnose=" .. tostring(glob.caught_pegnose) .. " found_evidence=" .. tostring(glob.found_evidence))
ar_checkpoint(25)
