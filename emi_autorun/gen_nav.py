#!/usr/bin/env python3
"""Writes emi_nav_data.lua: the sectors of every set of setx/*.setb for the Grim planner (autorun/ar_nav.lua, made into
generated/emi_nav_planner.lua by emi_nav_gen.py): the walk sectors (type 0x1000, funnels 0x1100 and stairs 0x1200 among them) and the
hot ones (0x8000: doors, triggers, cheat boxes), in the order of the file.
Each sector is { name, x, z, y, x, z, y, ... }: EMI's floor is x/z with y up, the planner's floor is its first two numbers with the
height third, so the corners are written as (x, z, y). They are in EMI's units; emi_nav.lua scales them to the planner's (AR_NAV_S).
    python gen_nav.py   (setx/ -> emi_nav_data.lua)
"""
import glob, os

exec(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'gen_floors.py')).read().split('\ndef num')[0])


def num(v):
    s = '%.5f' % v
    s = s.rstrip('0').rstrip('.')
    return s if s not in ('-0', '') else '0'


def row(nm, vs):
    assert '"' not in nm and chr(92) not in nm, nm
    return '{ "%s", %s }' % (nm, ', '.join('%s, %s, %s' % (num(v[0]), num(v[2]), num(v[1])) for v in vs))


out = ['-- GENERATED by gen_nav.py from setx/*.setb, do not edit: the walk sectors (w) and the hot sectors (h) of each set for the',
       '-- Grim planner, each set a function that returns them: { name, x, z, y, ... } (the floor x/z first, the height y third: the planner\'s axes), in EMI\'s units',
       'AR_NAV_EMI = { }']
for f in sorted(glob.glob(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'setx', '*.setb'))):
    key = os.path.basename(f)[:-5]
    walk = []
    hot = []
    for nm, typ, vis, vs in load(f):
        if len(vs) < 3:
            continue
        if typ & 0x1000:
            walk.append(row(nm, vs))
        elif typ & 0x8000:
            hot.append(row(nm, vs))
    # (each set in a function of its own: Lua 3.1 keeps the constants of a function in one table of limited size, and the numbers of
    # all the sets in the main chunk of the run overflowed it)
    out.append('AR_NAV_EMI["%s"] = function()\nreturn { w = {\n%s\n}, h = {\n%s\n} }\nend' % (key, ',\n'.join(walk), ',\n'.join(hot)))
dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'emi_nav_data.lua')
open(dst, 'w', newline='\n').write('\n'.join(out) + '\n')
print(len(out) - 3, 'sets', os.path.getsize(dst), 'bytes')
