-- EMI chapter 31: the tiny screw from the cavern, then to Inspector Canard in the Hall o' Justice
ar_load(30)
ar_log("=== EMI ch31 screw and Canard ===")
ar_wait_for_control()
ar_do("use", ban.topwindow)
ar_wait_for_control()
ar_state("luc")
ar_do("use", luc.lum_door2)
ar_wait_for_control()
ar_do("use", lum.lag_door)
ar_wait_for_control()
ar_do("use", lag.deepwater)
ar_wait_for(function() return ar_set_name() == "underwater lagoon" end, 20000, "the dive")
sleep_for(2500)
ar_wait_for_control()
ar_try_wait(function() return cutSceneLevel == 0 end, 30000)
sleep_for(1500)
-- (the glowing fishy lights the way: caught again with the ScupperWare, as in ch28)
a31_tries = 0
while props.scupperware.state ~= PROP_LOC2 and a31_tries < 8 do
	a31_tries = a31_tries + 1
	-- (the ScupperWare is in the hand before the fishies come by: they are only in reach for a moment)
	ar_hold(props.scupperware)
	ar_chase_offered(ulg.fishschool, 90000)
	ar_do("use", ulg.fishschool, props.scupperware)
	sleep_for(1000)
	ar_try_wait(function() return cutSceneLevel == 0 end, 20000)
	if props.scupperware.state ~= PROP_LOC2 then
		ar_do("use", props.scupperware)
		sleep_for(1000)
		ar_try_wait(function() return cutSceneLevel == 0 end, 20000)
		sleep_for(2000)
	end
end
ar_try_wait(function() return cutSceneLevel == 0 end, 30000)
sleep_for(1500)
-- (the cavern is entered by swimming into its mouth, the door sector in the west of the lagoon)
ar_walk_into_door("unc_door")
ar_wait_for(function() return ar_set_name() == "underground cavern" end, 30000, "the cavern")
sleep_for(1500)
-- (the entrance cutscene is skipped by the skipper with Escape, as a player does; the game gives the control back)
ar_wait_for_control()
ar_state("unc")
ar_do("use", unc.screw)
ar_wait_for_control()
ar_check(props.nosescrew.state == PROP_INV, "the screw in hand")
ar_do("use", unc.caveexit)
ar_wait_for_control()
ar_do("use", ulg.lag_door)
ar_wait_for_control()
ar_do("use", lag.lum_door)
ar_wait_for_control()
ar_do("use", lum.luc_door)
ar_wait_for_control()
ar_do("use", luc.hoj_door)
ar_wait_for_control()
ar_state("hoj")
-- (the verb starts the end of Act 1, movies and a cutscene that does not give control back: only sent, then the next scene is waited for)
ar_hold(props.nosescrew)
ar_approach(hoj.canard)
ar_send_verb("use", hoj.canard, "give the screw to Canard")
-- the end of Act 1 (movies, then Elaine in the mansion: dialog el15, the same as the start of Act 2)
ar_wait_for(function() return getglobal("el15") and el15.running end, 150000, "Elaine's dialog")
ar_dlg("el15")
sleep_for(2000)
AR_NO_SKIP = nil
ar_exhaust("el15", nil, 20)
ar_dlg_done("el15")
ar_state("after Elaine")
ar_checkpoint(31)
