#!/bin/sh
# Runs an EMI autorun script in the autorun build (SVM_DIR, default ~/scummvm-patched/build-opt: ../scummvm/build.sh, the same engine as the Grim
# autorun; the old Oct 27 build is SVM_DIR=/home/Joel/scummvm-emi/build-opt), apart from the grim runs:
# own config copy, own save path, own logs. The grim_tools/autorun libraries are only read, never changed.
#
#   run_emi.sh <script.lua> [timeout seconds] [extra scummvm options]
#
# Simulated clock (SIMFPS frames a second, flat out; SIMMS: every frame that many milliseconds). NOLOG seconds (default 30, real time) without a new line in the log
# end the run: it is stuck. Only this run's own scummvm.exe is ever killed (the grim runs are going on).
EM=$(cd "$(dirname "$0")" && pwd)
AR=$(cd "$EM/../autorun" && pwd)
INI_SRC="$APPDATA/ScummVM/scummvm.ini"
SVM_DEFAULT=/home/Joel/scummvm-patched/build-opt
SVM_EXE=./scummvm.exe
# (run from WSL: the Linux engine of ~/scummvm-wsl-emi (grim-tools.patch), ASAN=1 its build-asan, VALGRIND=1 its build-vg)
if grep -qi microsoft /proc/version 2>/dev/null; then
	WSL=1
	INI_SRC=/mnt/c/Users/Joel/AppData/Roaming/ScummVM/scummvm.ini
	SVM_DEFAULT=$HOME/scummvm-wsl-emi/$([ -n "$ASAN" ] && echo build-asan || ([ -n "$VALGRIND" ] && echo build-vg || echo build-opt))
	SVM_EXE=./scummvm
	# (VALGRIND=1: under valgrind's memcheck, its report in logs/<log>.vg; VGOPTS its options)
	[ -n "$VALGRIND" ] && SVM_EXE="valgrind ${VGOPTS:---leak-check=full --num-callers=30} --log-file=$EM/logs/${LOG:-$(basename "$1" .lua)}.vg ./scummvm"
	cygpath() { echo "$2"; }
	python() { python3 "$@"; }
fi
script="$1"; limit="${2:-600}"
[ $# -ge 2 ] && shift 2 || shift $#
name=$(basename "$script" .lua)
id=$$
mkdir -p "$EM/logs" "$EM/generated" "${SAVES:-$EM/saves}"
python "$EM/emi_nav_gen.py" "$EM/generated/emi_nav_planner_$id.lua" || exit 1

{
	echo "-- GENERATED by run_emi.sh, do not edit"
	echo "AR_CHAPTER = \"$name\""
	# TRICKS=<name>[,<name>...]: tricks of the speed runners, each off unless named (as ../autorun/mode.sh does for Grim): mug (the real
	# Monkey Mug taken without a fake one, act2_12). A run without them is not changed
	if [ -n "$TRICKS" ]; then
		echo "AR_TRICKS = { }"
		for t in $(echo "$TRICKS" | tr ',' ' '); do echo "AR_TRICKS[\"$t\"] = TRUE"; done
	fi
	[ -n "$NOSCREEN" ] && echo "AR_NOSCREEN = TRUE"
	cat "$EM/emi_prelude.lua"
	[ -z "$NOLIB" ] && cat "${ARLIB:-$AR/ar_lib.lua}"
	cat "$EM/emi_floors.lua" "$EM/emi_floors_fn.lua"
	# (the Grim planner made EMI's: emi_nav_gen.py, emi_nav_data.lua from gen_nav.py, emi_nav.lua)
	cat "$EM/generated/emi_nav_planner_$id.lua" "$EM/emi_nav_data.lua" "$EM/emi_nav.lua"
	cat "$EM/emi_lib.lua"
	for e in $EXTRA; do cat "$EM/$e"; done
	[ -n "$TRICKS" ] && echo "ar_log(\"tricks: $TRICKS\")"
	cat "$script"; echo
	echo "ar_finish()"
} > "$EM/generated/${name}_$id.lua"

cp "$INI_SRC" "$EM/generated/_scummvm_$id.ini"
# (a Linux build has no shaders or engine data built in: the shaders come from the game's extrapath, monkey4-patch.m4b from the
# extrapath of [scummvm], both in the engine's source)
if [ -n "$WSL" ]; then
	src=$(dirname "${SVM_DIR:-$SVM_DEFAULT}")
	sed -i "/^\[monkey4-win\]/{n;:a;/^\(path\|extrapath\)=/d;n;/^\[/!ba}" "$EM/generated/_scummvm_$id.ini"
	sed -i "/^\[monkey4-win\]/a path=/mnt/c/GOG Games/Escape from Monkey Island/\nextrapath=$src/engines/grim" "$EM/generated/_scummvm_$id.ini"
	sed -i "/^\[scummvm\]/a extrapath=$src/dists/engine-data" "$EM/generated/_scummvm_$id.ini"
fi
sed -i '/^\[monkey4-win\]/a speech_mute=true\nsubtitles=true\nfullscreen=false' "$EM/generated/_scummvm_$id.ini"
sed -i '/^\[scummvm\]/a enable_unsupported_game_warning=false' "$EM/generated/_scummvm_$id.ini"
[ -n "$DUMPDIR" ] && sed -i "/^\[monkey4-win\]/a dump_frames_dir=$DUMPDIR" "$EM/generated/_scummvm_$id.ini"
# (SIMMS: every simulated frame that many milliseconds, sim_frame_ms; 17 = the original under simtime)
[ -n "$SIMMS" ] && sed -i "/^\[monkey4-win\]/a sim_frame_ms=$SIMMS" "$EM/generated/_scummvm_$id.ini"

log="$EM/logs/${LOG:-$name}.log"
: > "$log"; : > "$log.times"
cd "${SVM_DIR:-$SVM_DEFAULT}" || exit 1
start=$(date +%s)
# (GDB=1: under gdb, which prints the stack of a crash into the log: the rare crash with exit status 127, a division by zero in
# Audio::Timestamp::msecs, Nov 10)
svm() {
	if [ -n "$GDB" ]; then
		exec gdb -batch ${GDBCMDS:+-x "$GDBCMDS"} -ex "set pagination off" -ex "set print thread-events off" -ex run -ex "thread apply all bt 25" --args $SVM_EXE "$@"
	fi
	exec $SVM_EXE "$@"
}
svm --config="$(cygpath -w "$EM/generated/_scummvm_$id.ini")" --savepath="$(cygpath -w "${SAVES:-$EM/saves}")" \
	--autorun="$(cygpath -w "$EM/generated/${name}_$id.lua")" --debugflags=scripts \
	$([ -z "$REALTIME" ] && echo --engine-speed=${ES:-0} --sim-fps=${SIMFPS:-60}) --show-fps "$@" monkey4-win > "$log" 2>&1 &
pid=$!
nolog=${NOLOG:-15}
# stuck = no NEW (distinct) AUTORUN line: a conversation that loops on the same lines is stuck too; no AUTORUN line (other than the waits' own "Starting wait"/"Waited") for NOLOG real seconds; the log itself also grows with the
# engine's chatter (sounds, chores), which says nothing about progress
last=-1; quiet=0
while kill -0 $pid 2>/dev/null; do
	sleep 1
	now=$(date +%s)
	# (LC_ALL=C for sort: the log has Latin-1 text, "Melee Island" with its accents, on which sort in a UTF-8 locale fails and
	# counts nothing; every run was then taken for stuck NOLOG seconds after the first such line)
	cur=$(grep -a "AUTORUN" "$log" | grep -a -v "Starting wait\|Waited" | sed "s/(Manny at [^)]*)//" | LC_ALL=C sort -u | wc -l)
	echo "$((now - start)) $cur" >> "$log.times"
	if [ "$cur" != "$last" ]; then last=$cur; quiet=0; else quiet=$((quiet + 1)); fi
	if [ $quiet -ge $nolog ]; then echo "NOLOG: no progress line for $nolog s, stopping" >> "$log"; kill $pid; sleep 1; kill -9 $pid 2>/dev/null; break; fi
	if [ $((now - start)) -ge $limit ]; then echo "TIMEOUT: $limit s, stopping" >> "$log"; kill $pid; sleep 1; kill -9 $pid 2>/dev/null; break; fi
done
wait $pid 2>/dev/null
st=$?
echo "scummvm exit status $st" >> "$log"
echo "scummvm exit after $(( $(date +%s) - start )) s" >> "$log"
grep -a -E 'AUTORUN|Autorun|rror|NOLOG|TIMEOUT|scummvm exit' "$log" | grep -a -v '__autorun__\|ar_watchdog' | tail -${TAIL:-60}
