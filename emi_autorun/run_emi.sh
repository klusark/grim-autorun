#!/bin/sh
# Runs an EMI autorun script in the autorun build (SVM_DIR, default ~/scummvm-autorun/build-opt: branch autorun, the same engine as the Grim
# autorun; the old Oct 27 build is SVM_DIR=/home/Joel/scummvm-emi/build-opt), apart from the grim runs:
# own config copy, own save path, own logs. The grim_tools/autorun libraries are only read, never changed.
#
#   run_emi.sh <script.lua> [timeout seconds] [extra scummvm options]
#
# Simulated clock (SIMFPS frames a second, flat out). NOLOG seconds (default 30, real time) without a new line in the log
# end the run: it is stuck. Only this run's own scummvm.exe is ever killed (the grim runs are going on).
EM=/c/Users/Joel/grim_tools/emi_autorun
AR=/c/Users/Joel/grim_tools/autorun
script="$1"; limit="${2:-600}"
[ $# -ge 2 ] && shift 2 || shift $#
name=$(basename "$script" .lua)
id=$$
mkdir -p "$EM/logs" "$EM/generated" "${SAVES:-$EM/saves}"

{
	echo "-- GENERATED by run_emi.sh, do not edit"
	echo "AR_CHAPTER = \"$name\""
	[ -n "$NOSCREEN" ] && echo "AR_NOSCREEN = TRUE"
	cat "$EM/emi_prelude.lua"
	[ -z "$NOLIB" ] && cat "${ARLIB:-$AR/ar_lib.lua}"
	cat "$EM/emi_floors.lua" "$EM/emi_floors_fn.lua"
	cat "$EM/emi_lib.lua"
	for e in $EXTRA; do cat "$EM/$e"; done
	cat "$script"; echo
	echo "ar_finish()"
} > "$EM/generated/${name}_$id.lua"

cp "$APPDATA/ScummVM/scummvm.ini" "$EM/generated/_scummvm_$id.ini"
sed -i '/^\[monkey4-win\]/a speech_mute=true\nsubtitles=true\nfullscreen=false' "$EM/generated/_scummvm_$id.ini"
sed -i '/^\[scummvm\]/a enable_unsupported_game_warning=false' "$EM/generated/_scummvm_$id.ini"
[ -n "$DUMPDIR" ] && sed -i "/^\[monkey4-win\]/a dump_frames_dir=$DUMPDIR" "$EM/generated/_scummvm_$id.ini"

log="$EM/logs/${LOG:-$name}.log"
: > "$log"; : > "$log.times"
cd "${SVM_DIR:-/home/Joel/scummvm-autorun/build-opt}" || exit 1
start=$(date +%s)
# (GDB=1: under gdb, which prints the stack of a crash into the log: the rare crash with exit status 127, a division by zero in
# Audio::Timestamp::msecs, Nov 10)
svm() {
	if [ -n "$GDB" ]; then
		exec gdb -batch -ex "set pagination off" -ex "set print thread-events off" -ex run -ex "thread apply all bt 25" --args ./scummvm.exe "$@"
	fi
	exec ./scummvm.exe "$@"
}
svm --config="$(cygpath -w "$EM/generated/_scummvm_$id.ini")" --savepath="$(cygpath -w "${SAVES:-$EM/saves}")" \
	--autorun="$(cygpath -w "$EM/generated/${name}_$id.lua")" --debugflags=scripts \
	$([ -z "$REALTIME" ] && echo --engine-speed=${ES:-0} --sim-fps=${SIMFPS:-60}) --show-fps "$@" monkey4-win > "$log" 2>&1 &
pid=$!
nolog=${NOLOG:-15}
# stuck = no NEW (distinct) AUTORUN line: a conversation that loops on the same lines is stuck too; no AUTORUN line (other than the waits' own "Starting wait"/"Waited") for NOLOG real seconds; the log itself also grows with the
# engine's chatter (sounds, chores), which says nothing about progress
last=-1; quiet=0
while kill -0 $pid 2>/dev/null; do
	sleep 1
	now=$(date +%s)
	cur=$(grep -a "AUTORUN" "$log" | grep -a -v "Starting wait\|Waited" | sed "s/(Manny at [^)]*)//" | sort -u | wc -l)
	echo "$((now - start)) $cur" >> "$log.times"
	if [ "$cur" != "$last" ]; then last=$cur; quiet=0; else quiet=$((quiet + 1)); fi
	if [ $quiet -ge $nolog ]; then echo "NOLOG: no progress line for $nolog s, stopping" >> "$log"; kill $pid; sleep 1; kill -9 $pid 2>/dev/null; break; fi
	if [ $((now - start)) -ge $limit ]; then echo "TIMEOUT: $limit s, stopping" >> "$log"; kill $pid; sleep 1; kill -9 $pid 2>/dev/null; break; fi
done
wait $pid 2>/dev/null
st=$?
echo "scummvm exit status $st" >> "$log"
echo "scummvm exit after $(( $(date +%s) - start )) s" >> "$log"
grep -a -E 'AUTORUN|Autorun|rror|NOLOG|TIMEOUT|scummvm exit' "$log" | grep -a -v '__autorun__\|ar_watchdog' | tail -${TAIL:-60}
