#!/usr/bin/env python3
"""Wraps an autorun script for the original Monkey4.exe: its Lua cannot parse the whole run as one function (a parse error with a
garbled token, at about 400 KB of a 1 MB function), so each library and each chapter becomes a function of its own (__ar_parts[i]),
and __autorun__ calls them in order in a task, as ScummVM's --autorun runs the whole file in one.
    orig_parts.py <head.lua> <body.lua> > out.lua   (head: the libraries and settings; body: the script, cut at its
    ar_log("=== lib / === file") lines)"""
import re, sys

head = open(sys.argv[1], encoding='latin-1').read()
body = open(sys.argv[2], encoding='latin-1').read()
parts = re.split(r'(?m)^(?=PrintDebug\("STAGE )', head)
pieces = []
for p in parts:
    if p.strip():
        pieces.append(p)
cut = re.split(r'(?m)^(?=ar_log\("=== (?:lib|file) )', body)
pieces += [c for c in cut if c.strip()]
out = ['-- GENERATED by run_orig.sh (orig_parts.py), do not edit', 'if __autorun__ then stop_script(__autorun__) end', '__ar_parts = { }']
for i, p in enumerate(pieces, 1):
    out.append('__ar_parts[%d] = function()\n%s\nend' % (i, p))
out.append('__autorun__ = function()\n\tlocal i = 1\n\twhile __ar_parts[i] do\n\t\t__ar_parts[i]()\n\t\ti = i + 1\n\tend\n\tar_finish()\nend')
out.append('start_script(__autorun__)')
sys.stdout.write('\n'.join(out) + '\n')
