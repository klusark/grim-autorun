#!/usr/bin/env python3
"""Writes emi_floors.lua: the walk sectors of every set of setx/*.setb (name, the vertices on the floor, the plane), for the Lua
GetFloorHeights of emi_floors_fn (the original Monkey4.exe has no GetFloorHeights; ScummVM's is a port addition).
    python gen_floors.py   (setx/ -> emi_floors.lua)
"""
import glob, os, struct

def load(path):
    d = open(path, 'rb').read(); o = 0
    def u32():
        nonlocal o; v = struct.unpack_from('<I', d, o)[0]; o += 4; return v
    for _ in range(u32()):
        o += 128; fl = u32(); o += fl + 12 + 16 + 12
    nl = u32(); o += nl * (32 + 12 + 16 + 4 + 4 + 4 + 12 + 16)
    secs = []
    for _ in range(u32()):
        nv = u32(); vs = [struct.unpack_from('<3f', d, o + 12 * i) for i in range(nv)]; o += nv * 12
        n = u32(); nm = d[o:o + n].split(b'\0')[0].decode('latin1'); o += n
        o += 4; vis = d[o]; o += 1; typ = u32(); nsp = u32(); o += 4 * nsp + 4
        secs.append((nm, typ, vis, vs))
    return secs

def num(v):
    s = '%.5f' % v
    s = s.rstrip('0').rstrip('.')
    return s if s not in ('-0', '') else '0'

out = ['-- GENERATED by gen_floors.py from setx/*.setb, do not edit: the walk sectors of each set, for the Lua GetFloorHeights',
       '-- { name, visible in the file, nx, ny, nz, y of vertex 1, x1, z1, x2, z2, ... } (the vertices on the x/z floor; the plane through vertex 1)',
       'AR_FLOORS = { }']
for f in sorted(glob.glob('setx/*.setb')):
    key = os.path.basename(f)[:-5]
    rows = []
    for nm, typ, vis, vs in load(f):
        if not (typ & 0x1000) or len(vs) < 3:
            continue
        # the normal as the port's Sector::load: (v1 - v0) x (v[n-1] - v0)
        a = [vs[1][i] - vs[0][i] for i in range(3)]; b = [vs[-1][i] - vs[0][i] for i in range(3)]
        nx = a[1] * b[2] - a[2] * b[1]; ny = a[2] * b[0] - a[0] * b[2]; nz = a[0] * b[1] - a[1] * b[0]
        L = (nx * nx + ny * ny + nz * nz) ** 0.5
        if L == 0 or abs(ny / L) < 1e-4:
            continue
        nx, ny, nz = nx / L, ny / L, nz / L
        assert '"' not in nm and chr(92) not in nm, nm
        cells = [nm]
        row = '{ "%s", %d, %s, %s, %s, %s' % (cells[0], 1 if vis else 0, num(nx), num(ny), num(nz), num(vs[0][1]))
        row += ', ' + ', '.join('%s, %s' % (num(v[0]), num(v[2])) for v in vs) + ' }'
        rows.append(row)
    out.append('AR_FLOORS["%s"] = {\n%s\n}' % (key, ',\n'.join(rows)))
open('emi_floors.lua', 'w', newline='\n').write('\n'.join(out) + '\n')
print(len(out) - 3, 'sets', os.path.getsize('emi_floors.lua'), 'bytes')
