-- What a skeleton bone does when its only animation is stopped (ScummVM bug 11794 follow-up): a lever of its own (the kitchen's
-- k_handle costume on a new actor, where the kitchen's lever was; that one is moved out of sight). A = never animated (bind pose),
-- B = pull_lever playing, held still 0.5 s in (time scale 0.001), C = 1.5 s after StopChore. The original keeps the pose the bone
-- had (C = B: a node with no animation channels left is not touched); ScummVM used to put it back on the bind pose.
ar_log("=== stop pose test ===")
ar_wait_for_control()
dofile("_jumpscripts.lua")
start_script(jump_script, "200")
ar_dlg("el15")
sleep_for(2000)
ar_exhaust("el15", nil, 20)
ar_dlg_done("el15")
ar_wait_for_control()
switch_to_set("lua")
sleep_for(2000)
lua.lead = 100
switch_to_set("kit")
sleep_for(1000)
guybrush:setpos(-3.2, 0, -4.2)
kit:current_setup(kit_cs_stove)
kit.handle:setpos(-3.64599991, -5, -6.79799986)
-- (the monkeys held still: only the test lever changes between the pictures)
kit.monkey.interest_actor:set_time_scale(0.001)
kit.monkey2:set_time_scale(0.001)
sp_lever = Actor:create(nil, nil, nil, "stop pose lever")
sp_lever:set_wear_chore("props/k_handle.cos")
sp_lever:put_in_set(kit)
sp_lever:setrot(0, -10, 0)
sp_lever:setpos(-3.64599991, 0.47299999, -6.79799986)
sleep_for(1500)
ar_log("POSE A")
sleep_for(5000)
sp_h = sp_lever:play_chore_looping("pull_lever")
sleep_for(500)
-- (held still while it plays: B is the pose the stop will find)
sp_lever:set_time_scale(0.001)
sleep_for(300)
ar_log("POSE B")
sleep_for(3000)
StopChore(sp_h)
sleep_for(1500)
ar_log("POSE C")
sleep_for(10000)
