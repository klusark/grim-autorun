#!/bin/sh
# Builds the whole-game autorun script for the ORIGINAL game: GRIMDATA/autorun_all.lua (the same
# libraries and chapters run_all.sh plays under ScummVM, in a task of their own) and
# GRIMDATA/grimpatch.bin, the file the original runs on Backspace+F12 (it needs the exe patched so
# that its Lua reads text: see PROGRESS.md). Usage: build_original.sh [first-chapter-prefix]
AR=/c/Users/Joel/grim_tools/autorun
GD="/c/GOG Games/GRIMDATA"
. "$AR/mode.sh" || exit 1
{
	# REAL=1: nothing is skipped and the voices are on; FRAMES=<ms>: a frame mark that often (tools/framecap.py takes the frames)
	echo "$MODE_LUA"
	[ -n "$FRAMES" ] && echo "AR_FRAMES = $FRAMES"
	cat <<'PRE'
-- GENERATED by build_original.sh from ar_lib.lua and the ch*.lua files, do not edit
-- A resume injects this while the autorun of the loaded save is still in ar_checkpoint, asleep between the save and the
-- end of the menu render mode that the save was made in: that end is done here, as the old autorun is stopped.
if AR_SAVING then
	RenderModeUser(nil)
	AR_SAVING = nil
end
if __autorun__ then
	stop_script(__autorun__)
end
-- the ScummVM-only builtins are development tools: the run may not call them (a call is a Lua error, the run fails)
IsSectorActive = nil
DumpSectors = nil

AR_KEEP_ALIVE = TRUE
-- (the stuck-movie guard of the skipper: a value that a save carried would stop a movie in the first frame after the load)
AR_MOVIE_START = nil
-- No progress text on the screen: the game frees the fonts at the change of the year and the original crashes when it draws
-- a text object whose font is gone. Text objects a loaded save brings back are taken away too.
if ar_screen_clear then
	ar_screen_clear()
	ar_shown_count = 0
end
AR_NOSCREEN = TRUE
AR_CHAPTER = "all"
AR_CONTINUE = TRUE
AR_TIMEOUT = 36000000
__autorun__ = function()
-- text only, no waiting for the voices
if SetSpeechMode and not AR_REAL then
	SetSpeechMode(TEXT_ONLY)
end
PRE
	# NOSCREEN=1: no progress text on the screen (it is made of text objects)
	[ -n "$NOSCREEN" ] && echo "AR_NOSCREEN = TRUE"
	echo "AR_NAV_ALWAYS = TRUE"
	if [ -n "$TRACE" ]; then
		echo "AR_TRACE = TRUE"
		cat <<'EOF2'
AR_WATCH_SET = nil
AR_WATCH_POS = nil
ar_watch = function()
	while TRUE do
		if system.currentSet ~= AR_WATCH_SET then
			AR_WATCH_SET = system.currentSet
			PrintDebug("AUTORUN WATCH set now " .. tostring(system.currentSet.name))
		end
		local p = manny:getpos()
		if AR_WATCH_POS and (abs(p.x - AR_WATCH_POS.x) + abs(p.y - AR_WATCH_POS.y)) > 0.8 then
			PrintDebug(format("AUTORUN WATCH jump (%.2f %.2f) -> (%.2f %.2f)", AR_WATCH_POS.x, AR_WATCH_POS.y, p.x, p.y))
		end
		AR_WATCH_POS = p
		break_here()
	end
end
start_script(ar_watch)
EOF2
	fi
	cur=""
	# TESTFILE=<file>: that script instead of the chapters (test_nav.lua), after the libraries
	if [ -n "$TESTFILE" ]; then
		cat "$AR/ar_lib.lua" "$AR/ar_helpers.lua" "$AR/ar_nav.lua" "$AR/nav_setfile.lua" $( [ -n "$RUNCASES" ] && [ -f "$AR/nav_cases_run.lua" ] && echo "$AR/nav_cases_run.lua" ) "$AR/nav_cases.lua" "$AR/ar_fixture.lua" "$AR/ar_nt_lib.lua" "$TESTFILE"
		NOCHAPTERS=1
	fi
	# EXTRALIB=<file>: a library after the helpers (a tracer: trace_manny.lua)
	[ -n "$EXTRALIB" ] && [ -z "$NOCHAPTERS" ] && cat "$EXTRALIB"
	for c in "$AR"/ch*.lua; do
		[ -n "$NOCHAPTERS" ] && break
		name=$(basename "$c" .lua)
		# chapters before the first one asked for are left out (the game is loaded from their checkpoint)
		if [ -n "$1" ] && [ "$name" \< "$1" ]; then continue; fi
		lib=ar_lib.lua
		if [ "$lib" != "$cur" ]; then
			cat "$AR/$lib"
			cat "$AR/ar_helpers.lua" "$AR/ar_full.lua"
			[ -n "$FULL" ] && cat "$AR"/ex*.lua
			if [ "$lib" = ar_lib.lua ]; then cat "$AR/ar_nav.lua" "$AR/nav_setfile.lua"; fi
			cur="$lib"
		fi
		echo "ar_log(\"=== chapter $name ===\")"
		echo "ar_frame_chapter(\"$name\")"
		# CUT=<line>: the first chapter starts at that line (a chapter failed half way and was finished by hand)
		if [ -n "$CUT" ] && [ -z "$cutdone" ]; then tail -n +"$CUT" "$c"; cutdone=1; else cat "$c"; fi
		echo 'if AR_FAILED then ar_finish() end'
	done
	echo 'ar_finish()'
	echo 'end'
	echo 'start_script(__autorun__)'
} > "$GD/autorun_all.lua"
python3 "$AR/mk_grimpatch.py"
ls -la "$GD/autorun_all.lua" "$GD/grimpatch.bin"
