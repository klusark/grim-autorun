-- Chapter 35: Velasco is told the vacancy, the union card and the strike are done.
-- Checkpoint in slot 51.

ar_load(34)
AR_NEW = TRUE
ar_log("start in " .. ar_set_name())
ar_wait_for_control()
-- the strike cutscene leaves Manny in front of the morgue: the detector to the coroner and the dog tags on the corpse (chapter 23 was this)
ar_describe()
ar_go(pc.mg_door, mg)
ar_wait_for_control()
ar_state("in the morgue")
-- the coroner is given the metal detector and sweeps the other corpse
ar_do("use", mg.membrillo_obj, sl.detector)
ar_wait_for(function() return membrillo.detecting end, 120000)
ar_wait_for_control()
ar_check(membrillo.detecting, "Membrillo has the detector")
-- the tags go on the first corpse; the detector finds them
ar_do("use", mg.corpse_1, si.dog_tags)
ar_wait_for(function() return made_vacancy end, 300000)
ar_check(made_vacancy, "a vacancy is made")
ar_wait_for(function() return system.currentSet ~= mg and cutSceneLevel == 0 end, 300000)
ar_wait_for_control()
ar_go(pc.ev_door, ev)
ar_go(ev.be_door, bw)
ar_go(bw.hb_door, hb)
ar_go(hb.lm_door, lm)
sleep_for(3000)
ar_wait_for_control()
ar_wait_for(function() return not find_script(lm.check_status) end, 300000)
ar_wait_for_control()
ar_state("in Limbo")
ar_do("use", lm.velasco_obj)
ar_wait_for(function() return ve2 and system.buttonHandler == ve2 end, 120000)
ar_pick_if(ve2, 90)
ar_pick_if(ve2, 100)
ar_pick_exit(ve2)
ar_wait_for_control()
ar_log("talked_readiness=" .. tostring(lm.talked_readiness))
ar_state("end of chapter 35")
ar_checkpoint(35)
