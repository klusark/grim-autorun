#!/usr/bin/env python3
"""rules_known.lua: the cases of test_rules.lua that differ from the original, with the reason of their group (the backlog of the edge rules).
   make_rules_known.py logs/test_rules.log > rules_known.lua      (the log of a ScummVM run against rules_expect.lua; a case fixed leaves the list: rerun)"""
import re, sys
POINT = "at an edge the original answers with the LAST sector that holds the point and holds a point up to about 1e-5 outside (FUN_004a6980); ScummVM answers the first, exactly"
KEY = "turn key held against a wall: the original turns by its own rate per frame and slides by the rules of FUN_004a8610; ScummVM differs by up to 7 cm"
SLIDE = "slide along an edge or a wall: the end differs by up to 1 cm and the heading by up to 1 degree (the sector walk of FUN_004a8610)"
ids = []
for line in open(sys.argv[1], errors='replace'):
    m = re.search(r'NAVTEST rules (\S+) FAIL', line)
    if m and 'AUTORUN' not in line.split('NAVTEST')[0]:
        ids.append(m.group(1))
print('-- GENERATED by tools/make_rules_known.py: the cases of test_rules.lua in which ScummVM differs from the original today (edge rules, not ported); do not edit')
print('AR_KNOWN = AR_KNOWN or { }')
for i in ids:
    why = POINT if i.startswith('point_') else (KEY if re.search(r'_k-?1$', i) else SLIDE)
    key = i if re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*', i) else '["%s"]' % i
    print('AR_KNOWN%s = "%s"' % ('.' + key if not key.startswith('[') else key, why))
