#!/usr/bin/env python3
"""Writes autorun/ROUTE.md from the log of a speed run made with SPEEDLOG=1.

    route_report.py [log, default logs/sr_now.log] [out, default ROUTE.md]

Per chapter: the frames (walking, waiting), the rooms with the frames spent in each, the way through them (the `go:` lines), the actions (COV do lines:
verb, thing, item, room) and the items gained and lost. Then across chapters: the rooms by frames and visits, the doors walked most, the life of every item
(chapter gained, chapter lost, chapters carried) and the pick-ups made in a room that an earlier chapter had passed through already.
"""
import os
import re
import sys
from collections import OrderedDict, defaultdict

AR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
log = sys.argv[1] if len(sys.argv) > 1 else os.path.join(AR, "logs", "sr_now.log")
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(AR, "ROUTE.md")

RE_CH = re.compile(r"\[(\d+)\] === chapter (\S+) ===")
RE_GO = re.compile(r"\[(\d+)\] go: (.+?) -> (.+?) \(holding")
RE_COV = re.compile(r"COV do \| (\w+) \| ([^|]*?) \| ([^|]*?) \| (.*?)\s*$")
RE_SPEED = re.compile(r"\[(\d+)\] SPEED (run|walk|stop)\s+(\d+) frames (.+?) \((-?[\d.]+) (-?[\d.]+)\) -> .*?control (\S+),")
RE_STATE = re.compile(r"\[(\d+)\] state (.+?): (.+?) \(-?[\d.]+ -?[\d.]+\) carrying \[(.*)\]")
RE_END = re.compile(r"\[(\d+)\] frames: (\d+)")

chapters = OrderedDict()
cur = None
end_frame = 0
for line in open(log, errors="replace", encoding="utf-8"):
    m = RE_CH.search(line)
    if m:
        cur = {"name": m.group(2), "start": int(m.group(1)), "rooms": OrderedDict(), "route": [], "acts": [], "inv": None, "first_room": None,
               "walk": 0, "wait_ctl": 0, "wait_cut": 0, "states": 0}
        chapters[cur["name"]] = cur
        continue
    m = RE_END.search(line)
    if m:
        end_frame = int(m.group(2))
    if cur is None:
        continue
    m = RE_GO.search(line)
    if m:
        a, b = m.group(2), m.group(3)
        if not cur["route"]:
            cur["route"].append(a)
        if cur["route"][-1] != b:
            cur["route"].append(b)
        continue
    m = RE_COV.search(line)
    if m:
        cur["acts"].append((m.group(1), m.group(2), m.group(3), m.group(4)))
        continue
    m = RE_SPEED.search(line)
    if m:
        kind, n, room, ctl = m.group(2), int(m.group(3)), m.group(4), m.group(7)
        cur["rooms"][room] = cur["rooms"].get(room, 0) + n
        if cur["first_room"] is None:
            cur["first_room"] = room
        if kind in ("run", "walk"):
            cur["walk"] += n
        elif ctl == "1":
            cur["wait_ctl"] += n
        else:
            cur["wait_cut"] += n
        continue
    m = RE_STATE.search(line)
    if m:
        items = [i.strip() for i in m.group(4).split(";") if i.strip()]
        cur["inv"] = items
        cur["states"] += 1

names = list(chapters)
for i, n in enumerate(names):
    s = chapters[n]["start"]
    e = chapters[names[i + 1]]["start"] if i + 1 < len(names) else end_frame
    chapters[n]["frames"] = e - s


def short(item):
    # "/motx068/scythe" -> "scythe"; "yellow balloon filled with a dark chemical" is kept
    return re.sub(r"^/[a-z0-9]+/", "", item)


def base(item):
    return re.sub(r"^/[a-z0-9]+/", "", item).split(" filled")[0]


def mmss(f):
    return "%d:%02d" % (f // 3600, (f // 60) % 60)


total = sum(c["frames"] for c in chapters.values())
prev = []
room_frames = defaultdict(int)
room_chapters = defaultdict(list)
room_first = {}
edges = defaultdict(int)
item_in = {}
item_out = {}
item_chap = defaultdict(list)
pick = []
visited_before = defaultdict(list)

for idx, (n, c) in enumerate(chapters.items()):
    inv = c["inv"] if c["inv"] is not None else prev
    now = {i for i in inv}
    gained = sorted(short(i) for i in now - set(prev))
    lost = sorted(short(i) for i in set(prev) - now)
    c["gained"], c["lost"], c["inv_n"] = gained, lost, len(now)
    for it in now - set(prev):
        item_in.setdefault(base(it), idx)
    for it in set(prev) - now:
        item_out[base(it)] = idx
    for it in now:
        item_chap[base(it)].append(idx)
    for r, f in c["rooms"].items():
        room_frames[r] += f
        room_chapters[r].append(idx)
    for a, b in zip(c["route"], c["route"][1:]):
        edges[(a, b)] += 1
    for (verb, thing, item, room) in c["acts"]:
        if verb == "pickUp":
            before = [j for j in sorted(set(room_chapters.get(room, []))) if j < idx]
            pick.append((idx, n, thing, room, before))
    prev = inv

with open(out, "w", newline="\n", encoding="utf-8") as o:
    w = o.write
    w("# Route of the speed run\n\n")
    w("Generated by `tools/route_report.py` from `%s`. %d frames, %s at 60 a second, %d chapters.\n\n" % (os.path.basename(log), total, mmss(total), len(chapters)))
    w("Frames are split into **walk** (the run and walk steps), **wait (ctl)** (standing with control: the planner, settling, the idle after an action) and\n")
    w("**wait (cut)** (standing without control: cutscenes, lines of speech, animations the game plays).\n\n")
    w("| # | chapter | frames | time | walk | wait (ctl) | wait (cut) | rooms |\n|---|---|---|---|---|---|---|---|\n")
    for i, (n, c) in enumerate(chapters.items(), 1):
        w("| %d | %s | %d | %s | %d | %d | %d | %d |\n" % (i, n, c["frames"], mmss(c["frames"]), c["walk"], c["wait_ctl"], c["wait_cut"], len(c["rooms"])))
    w("\n## Chapters\n")
    for i, (n, c) in enumerate(chapters.items(), 1):
        w("\n### %d. %s: %d frames (%s)\n\n" % (i, n, c["frames"], mmss(c["frames"])))
        w("- walk %d, wait with control %d, wait without control %d (frames in a room are the walking and waiting there; the rest is the loading and the start)\n" % (c["walk"], c["wait_ctl"], c["wait_cut"]))
        if c["route"]:
            w("- doors: %s\n" % " → ".join(c["route"]))
        rooms = sorted(c["rooms"].items(), key=lambda kv: -kv[1])
        if rooms:
            w("- rooms by frames: %s\n" % ", ".join("%s %d" % (r, f) for r, f in rooms))
        if c["acts"]:
            w("- actions:\n")
            for verb, thing, item, room in c["acts"]:
                w("  - %s %s%s @ %s\n" % (verb, thing, (" with " + item) if item else "", room))
        w("- items gained: %s\n" % (", ".join(c["gained"]) or "none"))
        w("- items lost: %s\n" % (", ".join(c["lost"]) or "none"))
        w("- carrying at the end: %d items\n" % c["inv_n"])

    w("\n## Rooms by frames\n\n| room | frames | time | chapters | which |\n|---|---|---|---|---|\n")
    for r, f in sorted(room_frames.items(), key=lambda kv: -kv[1]):
        ch = sorted(set(room_chapters[r]))
        w("| %s | %d | %s | %d | %s |\n" % (r, f, mmss(f), len(ch), ", ".join(str(j + 1) for j in ch)))

    w("\n## Doors walked most\n\n| from → to | times |\n|---|---|\n")
    for (a, b), k in sorted(edges.items(), key=lambda kv: -kv[1])[:40]:
        w("| %s → %s | %d |\n" % (a, b, k))

    w("\n## Items: gained, lost, carried\n\n| item | gained in | lost in | chapters carried |\n|---|---|---|---|\n")
    order = sorted(item_chap, key=lambda k: (item_in.get(k, -1), k))
    for k in order:
        gi = item_in.get(k)
        lo = item_out.get(k)
        w("| %s | %s | %s | %d |\n" % (k, ("%d %s" % (gi + 1, names[gi])) if gi is not None else "from the start", ("%d %s" % (lo + 1, names[lo])) if lo is not None else "kept to the end", len(item_chap[k])))

    w("\n## Pick-ups in a room that an earlier chapter had been in\n\n")
    w("An item that is picked up in a room the run already passed through chapters before. Whether it can be taken earlier depends on the story (the item may appear only\n")
    w("after an event); the list is where to look first.\n\n| pick-up | room | chapter | earlier chapters in the room |\n|---|---|---|---|\n")
    for idx, n, thing, room, before in pick:
        if before:
            w("| %s | %s | %d %s | %s |\n" % (thing, room, idx + 1, n, ", ".join(str(j + 1) for j in before)))
print("wrote %s: %d chapters, %d frames" % (out, len(chapters), total))
