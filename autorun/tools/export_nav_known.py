#!/usr/bin/env python3
"""Writes autorun/ar_nav_known.lua from the NAVLEARNED lines of run logs.

    export_nav_known.py [log ...]        default: logs/sr_new.log (a speed run, SPEEDLOG not needed)

A line is `NAVLEARNED <set file> <hot sector> <x> <y> <z>`: a hot sector that a script moved Manny out of, and where it put him
(ar_nav_learn). The links of the logs given are merged with the ones already in ar_nav_known.lua (a later log wins), so that the
file only grows; run it with a log of any run that went somewhere new and commit the result.
"""
import os
import re
import sys

AR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(AR, "ar_nav_known.lua")
logs = sys.argv[1:] or [os.path.join(AR, "logs", "sr_new.log")]

known = {}
if os.path.exists(OUT):
    for m in re.finditer(r'\["([^"]+)"\] = \{\s*(.*?)\n\t\}', open(OUT).read(), re.S):
        for h in re.finditer(r'(\w+) = \{ x = ([-\d.]+), y = ([-\d.]+), z = ([-\d.]+) \}', m.group(2)):
            known.setdefault(m.group(1), {})[h.group(1)] = (h.group(2), h.group(3), h.group(4))

pat = re.compile(r"NAVLEARNED (\S+) (\S+) (-?[\d.]+) (-?[\d.]+) (-?[\d.]+)")
for path in logs:
    with open(path, errors="replace") as f:
        for line in f:
            m = pat.search(line)
            if m and m.group(1) != "nil":
                known.setdefault(m.group(1), {})[m.group(2)] = m.group(3, 4, 5)

with open(OUT, "w", newline="\n") as o:
    o.write("-- GENERATED by tools/export_nav_known.py from the NAVLEARNED lines of run logs, do not edit.\n")
    o.write("-- The hot sectors that a script moves Manny out of, and where it puts him, per set file: the planner has these as links from the start\n")
    o.write("-- (nav_setfile.lua puts them in nav.learned), instead of finding them out when Manny has been carried.\n")
    o.write("AR_NAV_KNOWN = {\n")
    for sf in sorted(known):
        o.write('\t["%s"] = {\n' % sf)
        for hn in sorted(known[sf]):
            x, y, z = known[sf][hn]
            o.write("\t\t%s = { x = %s, y = %s, z = %s },\n" % (hn, x, y, z))
        o.write("\t},\n")
    o.write("}\n")
print("wrote %s: %d sets, %d links" % (OUT, len(known), sum(len(v) for v in known.values())))
