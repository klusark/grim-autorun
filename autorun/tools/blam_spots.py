#!/usr/bin/env python3
"""Makes autorun/ar_blam_spots.lua from the log of a learning run (BLAMLEARN=1, ar_tricks.lua).

    blam_spots.py <log> [out, default ar_blam_spots.lua] [--min <frames held, default 240>] [--keep <spots file to keep the spots of>]

A spot is a costume the game pushed onto Manny inside a cutscene and popped again inside one, held at least --min frames (the word blam holds it 3 s, 180 frames, so
it pays from about 200 on). One spot per anchor, the one held longest: a word typed for a later push of the same anchor would come after the first one changed the
timing. The spots of an older file given with --keep stay (a learning run made with blam on learns the anchors that had none).
"""
import re
import sys

args = sys.argv[1:]
minheld = 240
keep = None
if "--min" in args:
    i = args.index("--min"); minheld = int(args[i + 1]); del args[i:i + 2]
if "--keep" in args:
    i = args.index("--keep"); keep = args[i + 1]; del args[i:i + 2]
log = args[0]
out = args[1] if len(args) > 1 else "ar_blam_spots.lua"

push = re.compile(r"TRK push (\S+) key (.+?) off (-?\d+) cut (\S+) frame (\d+)")
pop = re.compile(r"TRK pop (\S+) cut (\S+) frame (\d+)")
stack = []
spots = {}
# (the frame of the last push or pop of any of Manny's costumes: the word may be typed only after it. A pop between the word and the push would take est.cos off in
# place of the game's own costume and leave that one on him)
last_event = -10 ** 9
for line in open(log, errors="replace", encoding="utf-8"):
    m = push.search(line)
    if m:
        f0 = int(m.group(5))
        stack.append((m.group(1), m.group(2), int(m.group(3)), m.group(4), f0, f0 - last_event - 1))
        last_event = f0
        continue
    m = pop.search(line)
    if m and stack:
        cos, key, off, cut, f0, gap = stack.pop()
        last_event = int(m.group(3))
        held = int(m.group(3)) - f0
        if cos == "est.cos" or key == "nil" or cut == "0" or m.group(2) == "0" or held < minheld:
            continue
        # (the word pops 180 frames after it is typed: typed up to 175 frames before the push, its pop comes just after it. Not before the anchor, nor before the
        # last costume event)
        lead = max(3, min(175, off, gap))
        if key not in spots or spots[key]["held"] < held:
            spots[key] = {"cos": cos, "off": off, "held": held, "lead": lead}

# (ar_blam_skip.txt: spots that are not to be cut, a part of a key on each line, # for a comment: the game's puzzle runs by the length of the animation)
skip = []
import os
sk = os.path.join(os.path.dirname(os.path.abspath(out)), "ar_blam_skip.txt")
if os.path.exists(sk):
    for line in open(sk, encoding="utf-8"):
        line = line.split("#")[0].strip()
        if line:
            skip.append(line)
spots = {k: v for k, v in spots.items() if not any(p in k for p in skip)}

kept = {}
if keep:
    rx = re.compile(r'AR_BLAM_SPOTS\["(.+?)"\] = \{ cos = "(.+?)", off = (-?\d+), held = (\d+)(?:, lead = (\d+))? \}')
    for line in open(keep, encoding="utf-8"):
        m = rx.search(line)
        if m:
            kept[m.group(1)] = {"cos": m.group(2), "off": int(m.group(3)), "held": int(m.group(4)), "lead": int(m.group(5) or 3)}
for k, v in spots.items():
    kept.setdefault(k, v)

with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("-- GENERATED by tools/blam_spots.py from %s: where TRICKS=blam types the word (ar_tricks.lua). Key: chapter|anchor|n; off: frames from the anchor to the\n" % log.replace("\\", "/").split("/")[-1])
    f.write("-- push of the costume; held: how long the game held it in the learning run; lead: how many frames before the push the word may be typed (no other\n")
    f.write("-- costume of Manny's is pushed or popped in between, and the pop of the word, 180 frames on, comes after the push)\n")
    f.write("AR_BLAM_SPOTS = AR_BLAM_SPOTS or { }\n")
    for k in sorted(kept, key=lambda k: (k.split("|")[0], k)):
        v = kept[k]
        f.write('AR_BLAM_SPOTS["%s"] = { cos = "%s", off = %d, held = %d, lead = %d }\n' % (k, v["cos"], v["off"], v["held"], v["lead"]))
print("wrote %s: %d spots (%d new), %d frames held in all" % (out, len(kept), len(spots), sum(v["held"] for v in kept.values())))
