#!/usr/bin/env python3
"""rules_expect.lua from the log of the ORIGINAL: make_rules_expect.py logs/orig_rules.log > rules_expect.lua"""
import re, sys
out = ['-- GENERATED by tools/make_rules_expect.py from a run of test_rules.lua on the ORIGINAL (the lines "NAVTEST rules_rec <id> ..."); do not edit',
       'AR_RULES_EXPECT = {']
seen = {}
for line in open(sys.argv[1], errors='replace'):
    m = re.search(r'NAVTEST rules_rec (\S+) (.*?)\s*$', line)
    if not m or 'AUTORUN' in line.split('NAVTEST')[0]:
        continue
    cid, rest = m.group(1), m.group(2)
    nums = rest.split()
    if len(nums) == 4 and all(re.fullmatch(r'-?[0-9.]+(e-?[0-9]+)?', n) for n in nums):
        seen[cid] = '{ %s, %s, %s, %s }' % tuple(nums)
    else:
        seen[cid] = '{ "%s" }' % rest
for cid in seen:
    out.append('\t%s = %s,' % (cid if re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*', cid) else '["%s"]' % cid, seen[cid]))
out.append('}')
print('\n'.join(out))
