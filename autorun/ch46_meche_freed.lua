-- Chapter 46 (Year 3): the vault. The scythe on the wall tab opens the secret door (the vault door has to be
-- closed again first), Manny drags the broadaxe through it into the vault interior with the held keys and
-- drops it on the tile, which breaks and frees Meche. Ends on the beach (bl). Checkpoint in slot 62.

AR_NEW = TRUE
ar_load(45)
ar_log("start in " .. ar_set_name())
ar_wait_for_control()
ar_go(vd.vo_door, vo)
ar_do("use", vo.open_door)
ar_wait_for_control()
ar_do("use", vo.wall_tab, mo.scythe)
ar_wait_for(function() return vo.secret_door.opened end, 90000)
ar_wait_for_control()
ar_check(vo.secret_door.opened, "the secret door is open")
ar_do("pickUp", vo.broadaxe)
ar_wait_for(function() return manny_has_axe end, 60000)
ar_wait_for_control()
ar_check(manny_has_axe, "Manny carries the axe")
ar_check(ar_axe_drive_to(-1.2, 1.03, 0.1, 40000, function() return system.currentSet ~= vo end) or system.currentSet ~= vo, "Manny drags the axe to the secret door")
ar_axe_drive_to(-1.6, 1.03, 0.05, 40000, function() return system.currentSet ~= vo end)
local pk = manny:getpos()
ar_log("after the drag " .. pk.x .. ", " .. pk.y .. " rot " .. manny:getrot().y .. " in " .. ar_set_name())
ar_wait_for(function() return system.currentSet == vi end, 30000)
ar_wait_for_control()
ar_check(system.currentSet == vi, "Manny is in the vault interior")
pk = manny:getpos()
ar_log("in the vault at " .. pk.x .. ", " .. pk.y)
ar_axe_drive_to(0.0, -0.388, 0.1, 40000)
sleep_for(300)
ar_axe_face(GetActorYawToPoint(manny.hActor, -0.236278996, -0.387933999, 0), 5, 20000)
ar_check(drop_test(), "Manny faces the tile at the right distance")
system.buttonHandler(ar_real_key("USE"), TRUE, nil)
ar_wait_for(function() return vi.tile_broken end, 30000)
ar_check(vi.tile_broken, "the tile is broken")
ar_wait_for(function() return cur_puzzle_state[41] end, 120000)
ar_wait_for_control()
ar_check(cur_puzzle_state[41], "Meche is free (puzzle state 41)")
ar_state("end of chapter 46")
ar_checkpoint(46)
