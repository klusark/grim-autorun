#!/bin/sh
# Runs one chapter script on the scratch saves in ./saves, without touching the real saves.
#
#   run_chapter.sh <chapter.lua> [timeout seconds] [extra scummvm options]
#
# The chapter is run after ar_lib.lua and loads the save it starts from by itself (ar_load, the
# first chapter starts a new game). The voices are muted (subtitles only) and the game runs in
# simulated time (SIMFPS frames a second, 60 unless set), never in a scaled clock. The log of the run is written to
# ./logs/<chapter>.log and the AUTORUN lines are shown at the end.
# Run it from an MSYS2 UCRT64 shell, scummvm is the one built in ~/scummvm/build.

AR=/c/Users/Joel/grim_tools/autorun
. "$AR/mode.sh" || exit 1
# A small window and a frame drawn in 64 (not the whole window, a frame in 8): the same run, 12% less cpu time and a third less wall time. Not where frames are
# captured (FRAMES) or the run is real (REAL), which want what a player sees; WIN= and RENDEREVERY= give the values.
[ -z "$FRAMES" ] && [ -z "$REAL" ] && [ -z "$REALTIME" ] && { : "${WIN:=640x480}"; : "${RENDEREVERY:=64}"; }
# (REALTIME=1: the game runs in real time, not in simulated time, and every frame is drawn)
chapter="$1"; limit="${2:-900}"
[ $# -ge 2 ] && shift 2 || shift $#
name=$(basename "$chapter" .lua)$LOGTAG
lib=${LIB:-ar_lib.lua}
mkdir -p "$AR/logs"

# the chapter id keeps the saver of an earlier chapter quiet when its save is loaded
{ echo "-- GENERATED by run_chapter.sh from ar_lib.lua and the chapter, do not edit"; echo "AR_CHAPTER = \"$name\""; echo "$MODE_LUA"; [ -n "$FRAMES" ] && echo "AR_FRAMES = $FRAMES"; [ -n "$NOSCREEN" ] && echo "AR_NOSCREEN = TRUE"; cat "$AR/$lib"; cat "$AR/ar_nav.lua" "$AR/nav_setfile.lua"; cat "$AR/ar_helpers.lua" "$AR/ar_full.lua"; { [ -n "$NAVDEBUG" ] || [ -n "$SPEEDLOG" ]; } && cat "$AR/ar_navdebug.lua"; [ -n "$FULL" ] && cat "$AR"/ex*.lua; for e in $EXTRA; do cat "$AR/$e"; done; cat "$chapter"; echo; echo "ar_finish()"; } > "$AR/generated/chapter_$$.lua"

INI="$AR/generated/_scummvm_$$.ini"
cp "$APPDATA/ScummVM/scummvm.ini" "$INI"
if [ -z "$REAL" ]; then
	[ -z "$NOMUTE" ] && { ini_set "$INI" speech_mute true; ini_set "$INI" subtitles true; ini_set "$INI" talkspeed 179; }
else
	ini_set "$INI" speech_mute false; ini_set "$INI" subtitles true
fi
[ "${PRELOAD:-1}" != 0 ] && ini_set "$INI" preload_data true
[ -z "$LOOSE" ] && ini_set "$INI" loose_files false
[ -n "$SIMMS" ] && ini_set "$INI" sim_frame_ms "$SIMMS"
[ -n "$DUMPDIR" ] && ini_set "$INI" dump_frames_dir "$DUMPDIR"
# TESTSETS=1: the hand-made sets of tests/sets (tools/mk_set.py) are read from there as datausr.lab
if [ -n "$TESTSETS" ]; then
	ini_set "$INI" datausr_load true
	ini_set "$INI" extrapath "$(cygpath -m "$AR/tests/sets")"
fi
[ -n "$NOEXACT" ] && ini_set "$INI" exact_edges false
[ -n "$NOKEYRULE" ] && ini_set "$INI" turn_key_rule false
# GRIMOFF="chore_timing path_planner ...": the rules of the engine that are switched off for the run (to find which one changes a result)
for r in $GRIMOFF; do ini_set "$INI" "$r" false; done
for r in $GRIMON; do ini_set "$INI" "$r" true; done
[ -n "$RENDEREVERY" ] && ini_set "$INI" sim_render_every "$RENDEREVERY"
[ -n "$JITTER" ] && ini_set "$INI" sim_jitter "$JITTER"
[ -n "$JITTERSEED" ] && ini_set "$INI" sim_jitter_seed "$JITTERSEED"
# NOSHORT=1: no zero-length frame after a change of set, a load or a save (the original has none)
[ -n "$NOSHORT" ] && ini_set "$INI" no_short_frame true
[ -n "$SHORTSIM" ] && ini_set "$INI" sim_short_frame true
[ -n "$WALLFPS" ] && ini_set "$INI" sim_wall_fps "$WALLFPS"
[ -n "$HOLDMS" ] && ini_set "$INI" sim_hold_ms "$HOLDMS"
[ -n "$MARKER" ] && ini_set "$INI" frame_marker true
[ -n "$NOPATCHR" ] && ini_set "$INI" no_patchr true
[ -n "$DUMPPATCHR" ] && ini_set "$INI" dump_patchr true

cd /home/Joel/scummvm/${SVM_BUILD:-build-opt}
# STALL=<seconds>: a run that logs nothing of the autorun for that long is killed (default 90; 0 = never)
export SCUMMVM_LUA_REMOTE="$AR/generated/remote_$$"
mkdir -p "$SCUMMVM_LUA_REMOTE"
: > "$AR/logs/$name.log"
sh "$AR/stall_watch.sh" "$AR/logs/$name.log" "${STALL:-$([ -n "$REALTIME" ] && echo 0 || ([ -n "$REAL" ] && echo 90 || echo 15))}" $$ &
stallpid=$!
start=$(date +%s)
timeout "$limit" ./scummvm.exe --config="$(cygpath -w "$AR/generated/_scummvm_$$.ini")" --savepath="$(cygpath -w "${SAVES:-$AR/saves}")" \
	--autorun="$(cygpath -w "$AR/generated/chapter_$$.lua")" --debugflags="${DEBUGFLAGS:-scripts}" \
	$([ -z "$REALTIME" ] && echo "--engine-speed=${ES:-0} --sim-fps=${SIMFPS:-60}") $([ -z "$NOFPS" ] && echo --show-fps) "$@" grim-win > "$AR/logs/$name.log" 2>&1
code=$?
kill $stallpid 2>/dev/null
echo "scummvm exit: $code after $(( $(date +%s) - start )) s" >> "$AR/logs/$name.log"
grep -E 'AUTORUN|Autorun|rror|scummvm exit' "$AR/logs/$name.log" | grep -v '__autorun__\|ar_watchdog'
