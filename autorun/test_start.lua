-- DEV: in what order do a started script and the one that started it run (log lines TS ...)
ar_load(19)
ar_wait_for_control()
ts_child = function(name)
	PrintDebug("TS " .. name .. " child begins\n")
	break_here()
	PrintDebug("TS " .. name .. " child after its first yield\n")
end
PrintDebug("TS A before start_script\n")
start_script(ts_child, "A")
PrintDebug("TS A after start_script\n")
break_here()
PrintDebug("TS A after the first break_here\n")
break_here()
PrintDebug("TS A after the second break_here\n")
PrintDebug("TS B before start_script\n")
start_script(ts_child, "B")
PrintDebug("TS B after start_script\n")
sleep_for(100)
PrintDebug("TS B after sleep_for\n")
PrintDebug("TS DONE\n")
