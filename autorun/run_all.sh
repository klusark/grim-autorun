#!/bin/sh
# Plays every chapter in one run, from a new game. With SAVE=1 it writes the checkpoint save (grim01.gsv ...) into ./saves at the end of each
# chapter and goes on playing (to play a chapter by itself with run_chapter.sh); by default it does not save.
#
#   run_all.sh [timeout seconds] [extra scummvm options]
#
# Same speed and mute settings as run_chapter.sh (simulated time, SIMFPS frames a second). The chapters run in
# file name order, one after the other, and the run stops at the first chapter that fails.
# The log goes to ./logs/all.log.

AR=/c/Users/Joel/grim_tools/autorun
. "$AR/mode.sh" || exit 1
# A small window and a frame drawn in 64 (not the whole window, a frame in 8): the same run, 12% less cpu time and a third less wall time. Not where frames are
# captured (FRAMES) or the run is real (REAL), which want what a player sees; WIN= and RENDEREVERY= give the values.
[ -z "$FRAMES" ] && [ -z "$REAL" ] && { : "${WIN:=640x480}"; : "${RENDEREVERY:=64}"; }
# (a run in real time, REALTIME=1, has no time limit and no stall watch unless asked for: it goes on until it ends or is killed; timeout 0 is no limit)
limit="${1:-1800}"
[ -n "$REALTIME" ] && [ $# -eq 0 ] && limit=0
[ $# -ge 1 ] && shift
mkdir -p "$AR/logs" "$AR/saves_new" "${SAVES:-$AR/saves}"

{
	echo "-- GENERATED by run_all.sh from ar_lib.lua and the ch*.lua files, do not edit"
	echo 'AR_CHAPTER = "all"'
	echo 'IsSectorActive = nil DumpSectors = nil '
	# FROM=<n>: starts at chapter n, from the checkpoint the chapter before it saved (SAVE=1 of an earlier run; the first chapter loads it, the game plays on from there)
	[ -z "$FROM" ] && echo 'AR_CONTINUE = TRUE'
	# SAVE=1: the checkpoints grim01.gsv ... are saved at the end of each chapter (to play a chapter by itself with run_chapter.sh); a run does not save by default
	[ -z "$SAVE" ] && echo 'AR_NOSAVE = TRUE'
	# REAL=1: nothing is skipped and the voices are on; FRAMES=<ms>: ScummVM writes a frame that often (to DUMPDIR)
	echo "$MODE_LUA"
	[ -n "$FRAMES" ] && echo "AR_FRAMES = $FRAMES"
	# (the autorun's own watchdog fails a run after this much game time: 10 hours, none in real time)
	if [ -n "$REALTIME" ]; then echo 'AR_TIMEOUT = 1000000000000'; else echo 'AR_TIMEOUT = 36000000'; fi
	# NOSCREEN=1: no progress text drawn on the screen (for a video)
	[ -n "$NOSCREEN" ] && echo 'AR_NOSCREEN = TRUE'
	cur=""
	for c in "$AR"/ch*.lua; do
		name=$(basename "$c" .lua)
		# UPTO=<n>: only the chapters up to number n (UPTO=6 is act 1, Year 1), for a quicker run
		if [ -n "$UPTO" ]; then
			num=${name#ch}; num=${num%%[!0-9]*}
			[ -n "$num" ] && [ $((10#$num)) -gt "$UPTO" ] && break
		fi
		# FROM=<n>: the chapters before number n are left out
		if [ -n "$FROM" ]; then
			num=${name#ch}; num=${num%%[!0-9]*}
			[ -n "$num" ] && [ $((10#$num)) -lt "$FROM" ] && continue
		fi
		lib=ar_lib.lua
		if [ "$lib" != "$cur" ]; then
			# (the extra library comes first, as it does in build_original.sh: the order of the tasks of a frame is the order they were started in)
			[ -n "$EXTRALIB" ] && cat "$AR/$EXTRALIB"
			cat "$AR/$lib" "$AR/ar_nav.lua" "$AR/nav_setfile.lua" "$AR/ar_nav_known.lua"
			cat "$AR/ar_helpers.lua" "$AR/ar_full.lua"
			{ [ -n "$NAVDEBUG" ] || [ -n "$SPEEDLOG" ]; } && cat "$AR/ar_navdebug.lua"
			[ -n "$FULL" ] && cat "$AR"/ex*.lua
			cur="$lib"
		fi
		echo "ar_log(\"=== chapter $name ===\")"
		echo "ar_frame_chapter(\"$name\")"
		cat "$c"
		echo 'if AR_FAILED then ar_finish() end'
	done
	echo 'ar_finish()'
} > "$AR/generated/all_$$.lua"

INI="$AR/generated/_scummvm_$$.ini"
cp "$APPDATA/ScummVM/scummvm.ini" "$INI"
if [ -z "$REAL" ]; then
	ini_set "$INI" speech_mute true; ini_set "$INI" subtitles true; ini_set "$INI" talkspeed 179
else
	# (a speech_mute=true in the user's own scummvm.ini would keep the voices off: ini_set takes the old line out and sets false)
	ini_set "$INI" speech_mute false; ini_set "$INI" subtitles true
fi
# (the data archives are read into memory at the start: Year 1 takes a tenth less time; PRELOAD=0 for a run without it)
[ "${PRELOAD:-1}" != 0 ] && ini_set "$INI" preload_data true
# (the files that lie loose in the game folder are not used: LOOSE=1 brings them back; the archives are all there is: a loose file of the name of an archive member used to take its place)
[ -z "$LOOSE" ] && ini_set "$INI" loose_files false
[ -n "$SIMMS" ] && ini_set "$INI" sim_frame_ms "$SIMMS"
[ -n "$RENDEREVERY" ] && ini_set "$INI" sim_render_every "$RENDEREVERY"
[ -n "$JITTER" ] && ini_set "$INI" sim_jitter "$JITTER"
[ -n "$JITTERSEED" ] && ini_set "$INI" sim_jitter_seed "$JITTERSEED"
# NOSHORT=1: no zero-length frame after a change of set, a load or a save (the original has none); SHORTSIM=1: the zero frame in a simulated run too
[ -n "$NOSHORT" ] && ini_set "$INI" no_short_frame true
[ -n "$SHORTSIM" ] && ini_set "$INI" sim_short_frame true
[ -n "$WALLFPS" ] && ini_set "$INI" sim_wall_fps "$WALLFPS"
[ -n "$HOLDMS" ] && ini_set "$INI" sim_hold_ms "$HOLDMS"
[ -n "$MARKER" ] && ini_set "$INI" frame_marker true
[ -n "$DUMPDIR" ] && ini_set "$INI" dump_frames_dir "$DUMPDIR"
[ -n "$NOPATCHR" ] && ini_set "$INI" no_patchr true
[ -n "$DUMPPATCHR" ] && ini_set "$INI" dump_patchr true
# WIN=640x480 sets the size of the window (it plays in a window, not fullscreen)
if [ -n "$WIN" ]; then
	sed -i "s/^last_window_width=.*/last_window_width=${WIN%x*}/; s/^last_window_height=.*/last_window_height=${WIN#*x}/; s/^window_maximized=.*/window_maximized=false/" "$INI"
	ini_set "$INI" fullscreen false
fi

cd /home/Joel/scummvm/${SVM_BUILD:-build-opt}
# STALL=<seconds>: a run that logs nothing of the autorun for that long is killed (default 90; 0 = never)
export SCUMMVM_LUA_REMOTE="$AR/generated/remote_$$"
mkdir -p "$SCUMMVM_LUA_REMOTE"
: > "$AR/logs/${LOG:-all}.log"
sh "$AR/stall_watch.sh" "$AR/logs/${LOG:-all}.log" "${STALL:-$([ -n "$REALTIME" ] && echo 0 || ([ -n "$REAL" ] && echo 90 || echo 15))}" $$ &
stallpid=$!
start=$(date +%s)
timeout "$limit" ./scummvm.exe --config="$(cygpath -w "$AR/generated/_scummvm_$$.ini")" --savepath="$(cygpath -w "${SAVES:-$AR/saves}")" \
	--autorun="$(cygpath -w "$AR/generated/all_$$.lua")" --debugflags="${DEBUGFLAGS:-scripts}" \
	$([ -z "$REALTIME" ] && echo "--engine-speed=${ES:-0} --sim-fps=${SIMFPS:-60}") $([ -z "$NOFPS" ] && echo --show-fps) "$@" grim-win 2>&1 	| python "$AR/tools/logts.py" "$AR/logs/${LOG:-all}.ts" | awk -v out="$AR/logs/${LOG:-all}.log" -v times="$AR/logs/${LOG:-all}_times.txt" -v t0="$start" '{ print > out; if (/=== chapter/) { n = systime() - t0; print n, $0 > times; fflush(times) } fflush(out) }'
code=$?
kill $stallpid 2>/dev/null
echo "scummvm exit: $code after $(( $(date +%s) - start )) s" >> "$AR/logs/${LOG:-all}.log"
grep -E 'AUTORUN|Autorun|rror|scummvm exit' "$AR/logs/${LOG:-all}.log" | grep -v '__autorun__\|ar_watchdog'
