-- Chapter 19: the turkey baster from the high roller kitchen, filled with dishwater at the Blue
-- Casket's kitchen sink (the way there passes the kitchen camera: the kiss cutscene). Checkpoint 35.

ar_load(18)
AR_NEW = TRUE
ar_log("start in " .. ar_set_name())
ar_wait_for_control()
ar_go(hl.hk_door, hk)
ar_wait_for_control()
ar_do("pickUp", hk.turkey_baster)
ar_check(hk.turkey_baster.owner == manny, "Manny has the turkey baster")
ar_go(hk.hl_door, hl)
ar_hl_elevator()
ar_go(hl.hh_door, hh)
ar_go(hh.tb_door, tb)
ar_wait_for_control()
ar_tw_exit()
ar_go(tb.ts_door, ts)
ar_go(ts.tx_door, tx)
ar_go(tx.xb_door, xb)
ar_go(xb.hb_door, hb)
ar_go(hb.bw_door, bw)
ar_go(bw.be_door, be)
ar_go(be.bi_door, bi)
ar_wait_for_control()
ar_state("in the Blue Casket")
-- on the way to the kitchen door the camera changes: Nick and Lola kiss in the kitchen door, Manny
-- is there with the camera and the photographer talks (Olivia)
ar_walk_to(-0.4, -1.4, 0.15, function() return bi.seen_kiss end)
ar_wait_for(function() return bi.seen_kiss end, 60000)
ar_check(bi.seen_kiss, "Manny saw the kiss")
ar_wait_for_control()
-- (after the skipped cutscene the original leaves Manny by Olivia without the talk: a player speaks to her)
if not ar_try_wait(function() return ol1 and system.buttonHandler == ol1 end, 8000) then
	ar_do("use", bi.olivia_obj)
end
ar_wait_for(function() return ol1 and system.buttonHandler == ol1 end, 120000)
ar_pick_exit(ol1)
ar_wait_for_control()
ar_state("after the kiss")
ar_go(bi.bk_door, bk)
ar_wait_for_control()
ar_wait_for(function() return bk.seen_water end, 60000)
ar_wait_for_control()
ar_do("use", bk.sink, hk.turkey_baster)
ar_wait_for(function() return hk.turkey_baster.full end, 60000)
ar_wait_for_control()
ar_check(hk.turkey_baster.full, "the baster is full of dishwater")
ar_state("end of chapter 19")
ar_checkpoint(19)
