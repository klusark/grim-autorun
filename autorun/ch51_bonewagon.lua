-- Chapter 51 (Year 4): the Bone Wagon is jammed by dominoes in its garage (jb). Liquid nitrogen from the
-- cabinet of Toto's shop (si), the ship in a bottle from Velasco (lm), the bottle filled at the keg in
-- the Blue Casket kitchen (bk), Glottis drinks it on the bridge (xb) and throws up gelatin over the dominoes,
-- the nitrogen freezes it (puzzle state 49), then the dynamite at the back is defused and the wagon goes
-- (cutscene vivamaro) to the New Headquarters (nq). Checkpoint in slot 67.

AR_NEW = TRUE
ar_load(51)
ar_log("start in " .. ar_set_name())
ar_wait_for_control()
ar_go(jb.xb_door, xb)
ar_wait_for_control()
ar_go(xb.se_door, se)
ar_wait_for_control()
ar_go(se.si_door, si)
ar_wait_for_control()
ar_do("use", si.cabinet)
ar_wait_for_control()
ar_check(si.nitrogen.owner == manny, "Manny has the liquid nitrogen")
ar_go(si.ladder, se)
ar_wait_for_control()
ar_go(se.sd_door, xb)
ar_wait_for_control()
ar_go(xb.hb_door, hb)
ar_wait_for_control()
ar_go(hb.lm_door, lm)
ar_wait_for_control()
ar_do("pickUp", lm.bottle)
ar_wait_for_control()
ar_check(lm.bottle.owner == manny, "Manny has the ship in a bottle")
ar_go(lm.hb_door, hb)
ar_wait_for_control()
ar_go(hb.bw_door, bw)
ar_wait_for_control()
ar_go(bw.be_door, be)
ar_wait_for_control()
ar_go(be.bi_door, bi)
ar_wait_for_control()
ar_go(bi.bk_door, bk)
ar_wait_for_control()
ar_do("use", bk.keg, lm.bottle)
ar_wait_for_control()
ar_check(lm.bottle.full, "the bottle is full")
ar_go(bk.bi_door, bi)
ar_wait_for_control()
ar_go(bi.be_door, be)
ar_wait_for_control()
ar_go(be.bw_door, bw)
ar_wait_for_control()
ar_go(bw.hb_door, hb)
ar_wait_for_control()
ar_go(hb.xb_door, xb)
ar_wait_for_control()
ar_do_retry("use", xb.glottis_obj, lm.bottle, 6)
ar_wait_for(function() return glottis.nauseated end, 120000)
ar_wait_for_control()
ar_check(glottis.nauseated, "Glottis drank the bottle")
ar_do_retry("use", xb.glottis_obj, nil, 6)
ar_wait_for(function() return jb.poured end, 120000)
ar_wait_for_control()
ar_check(jb.poured, "the dominoes are covered in gelatin")
ar_go(xb.jb_door, jb)
ar_wait_for_control()
ar_do("use", jb.dominos, si.nitrogen)
ar_wait_for(function() return jb.frozen end, 120000)
ar_wait_for_control()
ar_check(cur_puzzle_state[49], "the gelatin is frozen (puzzle state 49)")
AR_CONTROL_TIMEOUT = 600000
ar_do("pickUp", jb.dynamite)
ar_wait_for(function() return system.currentSet == nq end, 600000)
ar_wait_for_control()
AR_CONTROL_TIMEOUT = nil
ar_state("end of chapter 51")
ar_checkpoint(52)
