-- Chapter 17: Charlie at the casino table gives the ticket printer and, since Velasco told about
-- the union card, the V.I.P. pass. Checkpoint in slot 33.

ar_load(16)
AR_NEW = TRUE
ar_log("start in " .. ar_set_name())
ar_wait_for_control()
ar_go(dd.bw_door, bw)
ar_go(bw.ev_door, ev, -2.49, -2.35, 0.2)
ar_go(ev.ce_door, ce, -0.5, -0.85, 0.05)
ar_go(ce.cc_door, cc)
ar_go(cc.ci_door, ci)
ar_wait_for_control()
ar_describe()
ar_go(ci.cn_door, cn)
ar_wait_for_control()
ar_describe()
ar_do("use", cn.charlie_obj)
ar_wait_for(function() return ch1 and system.buttonHandler == ch1 end, 60000)
ar_pick_if(ch1, 100)
ar_pick_if(ch1, 120)
ar_pick_if(ch1, 130)
ar_pick_if(ch1, 160)
ar_wait_for(function() return cn.pass.owner == manny end, 60000)
ar_check(cn.printer.owner == manny, "Manny has the ticket printer")
ar_check(cn.pass.owner == manny, "Manny has the V.I.P. pass")
ar_pick_exit(ch1)
ar_wait_for_control()
ar_state("end of chapter 17")
ar_checkpoint(17)
